def _frame(case: dict[str, Any]) -> pd.DataFrame:
    return pd.DataFrame(case["data"], columns=case["items"], dtype=float)


def _arr(values: list[float | None]) -> np.ndarray:
    return np.array([np.nan if v is None else v for v in values], dtype=float)


def _case(section: list[dict[str, Any]], name: str) -> dict[str, Any]:
    return next(c for c in section if c["name"] == name)


def _flags(steps: list[list[bool]], items: list[str]) -> pd.DataFrame:
    return pd.DataFrame(np.array(steps, dtype=bool).reshape(len(steps), len(items)), columns=items)


