    np.testing.assert_allclose(expected, [r["chi2_correct"] for r in ref], rtol=EXACT)
    assert small.any() == (name == "sim_2pl")
    np.testing.assert_allclose(res.table["odds_ratio"], [r["odds_ratio"] for r in ref], rtol=EXACT)


