def _mh_difference(case: dict[str, Any]) -> np.ndarray:
    """sum_k A_k - E(A_k) per item, total-score matching, strata of more than one respondent."""
    y = np.array(case["data"], dtype=float)
    ref = np.array(case["group"]) != case["focal"]
    total = y.sum(axis=1)
    out = []
    for j in range(y.shape[1]):
        diff = 0.0
        for s in np.unique(total):
            rows = total == s
            if rows.sum() < 2:
                continue
            observed = np.sum(rows & ref & (y[:, j] == 1))
            diff += observed - ref[rows].sum() * y[rows, j].sum() / rows.sum()
        out.append(diff)
    return np.array(out)


@pytest.mark.parametrize("name", MH_CASES)
@pytest.mark.parametrize("correct", [True, False])
def test_mantel_haenszel_matches_difmh(name: str, correct: bool) -> None:
    case = _case(_reference()["mantel_haenszel"]["cases"], name)
    ref = next(r for r in case["plain"] if r["correct"] is correct)
    res = mantel_haenszel(
        _frame(case), group=case["group"], focal=case["focal"], continuity_correction=correct
    )
    t = res.table
    assert list(t["item"]) == case["items"]
    chi2 = _arr(ref["chi2"])
    p = _arr(ref["p"])
    np.testing.assert_allclose(t["chi2"], chi2, rtol=EXACT)
    np.testing.assert_allclose(t["p"], p, rtol=1e-8, atol=1e-15)
    np.testing.assert_allclose(t["odds_ratio"], _arr(ref["alpha_mh"]), rtol=EXACT)
    np.testing.assert_allclose(t["log_odds_ratio_se"] ** 2, _arr(ref["var_lambda"]), rtol=EXACT)
    np.testing.assert_allclose(t["delta"], -2.35 * np.log(_arr(ref["alpha_mh"])), rtol=EXACT)
    np.testing.assert_allclose(t["delta_se"], 2.35 * np.sqrt(_arr(ref["var_lambda"])), rtol=EXACT)
    assert list(t["flagged"]) == ref["flagged"]
    assert res.n_iter == 0 and res.converged and res.anchor_items == case["items"]


@pytest.mark.parametrize("name", MH_CASES)
def test_mantel_haenszel_matches_mantelhaen_test(name: str) -> None:
    case = _case(_reference()["mantel_haenszel"]["cases"], name)
    ref = case["mantelhaen"]
    plain = mantel_haenszel(
        _frame(case), group=case["group"], focal=case["focal"], continuity_correction=False
    )
    np.testing.assert_allclose(plain.table["chi2"], [r["chi2"] for r in ref], rtol=EXACT)
    # mantelhaen.test drops the continuity correction when |sum A - sum E(A)| < 1/2 (difR and
