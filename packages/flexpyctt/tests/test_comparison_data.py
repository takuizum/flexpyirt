"""Comparison data (DESIGN.md §16.15, VALIDATION.md V29).

``tests/reference/v29_comparison_data.json`` is generated by
``validation/r/m5_comparison_data_reference.R`` with EFAtools 1.1.0: its principal axis
factoring, its population generator fed with exported random draws (one factor, compared
exactly), ``CD()`` on three data sets and R's ``wilcox.test`` on its RMSE columns.
"""

from __future__ import annotations

import json
from functools import cache
from typing import Any

import numpy as np
import pytest

from flexpyctt import comparison_data
from flexpyctt._comparison_data import (
    eigenvalue_rmse,
    generate_population,
    paf_loadings,
    wilcoxon_less,
)
from flexpyctt.errors import SpecificationError
from reference_data import REFERENCE_DIR, load_reference


@cache
def _reference() -> dict[str, Any]:
    return load_reference("v29_comparison_data")


@cache
def _raw(name: str) -> dict[str, Any]:
    return dict(json.loads((REFERENCE_DIR / name).read_text(encoding="utf-8")))


def _cd_case(name: str) -> dict[str, Any]:
    return next(c for c in _reference()["cd"] if c["name"] == name)


def test_paf_matches_efatools() -> None:
    v28 = _raw("v28_efa_hull.json")
    corr = np.asarray(next(c for c in v28["cases"] if c["name"] == "sim_3f")["correlation"])
    for fit in _reference()["paf"]["fits"]:
        lam = paf_loadings(corr, fit["k"])
        lam_ref = np.asarray(fit["loadings"])
        np.testing.assert_allclose(lam @ lam.T, lam_ref @ lam_ref.T, rtol=0, atol=1e-12)


def test_generator_reproduces_efatools_from_the_same_draws() -> None:
    gen = _reference()["generator"]
    v24 = _raw("v24_polychoric.json")
    x = np.asarray(
        next(c for c in v24["cases"] if c["name"] == "polychoric_mixed")["data"], dtype=float
    )
    pop, rmse = generate_population(
        np.corrcoef(x, rowvar=False),
        np.asarray(gen["dists"]),
        np.asarray(gen["shared"]),
        np.asarray(gen["unique"]),
    )
    np.testing.assert_array_equal(pop, np.asarray(gen["population"]))
    assert 0 < rmse < 0.2
    # Marginals are exactly the resampled observed values.
    np.testing.assert_array_equal(np.sort(pop, axis=0), np.asarray(gen["dists"]))


@pytest.mark.parametrize("name", ["sim_3f", "polychoric_mixed", "tetrachoric_sim"])
def test_wilcoxon_matches_r(name: str) -> None:
    case = _cd_case(name)
    rmse = [np.asarray(col) for col in case["rmse"]]
    for k in range(2, case["tested"] + 1):
        got = wilcoxon_less(rmse[k - 1], rmse[k - 2])
        assert got == pytest.approx(case["wilcox_p"][k - 2], rel=1e-10, abs=1e-300)


@pytest.mark.parametrize("name", ["sim_3f", "polychoric_mixed", "tetrachoric_sim"])
@pytest.mark.parametrize("seed", [0, 1])
def test_comparison_data_agrees_with_efatools(name: str, seed: int) -> None:
    case = _cd_case(name)
    data = np.asarray(case["data"], dtype=float)
    res = comparison_data(data, rng=seed)
    assert res.n_factors == case["n_factors"]
    # Every k is judged on one generated population. For the retained k the mean RMSE is stable
    # across populations (15%); for a rejected extra factor it is not (seeds give 0.044 to 0.072
    # where EFAtools' draw gave 0.048), so that column only gets a loose check.
    kept = min(res.n_factors, case["tested"])
    mean_rmse = res.rmse.mean().to_numpy()
    np.testing.assert_allclose(mean_rmse[:kept], case["mean_rmse"][:kept], rtol=0.15)
    tested = min(res.rmse.shape[1], case["tested"])
    np.testing.assert_allclose(mean_rmse[kept:tested], case["mean_rmse"][kept:tested], rtol=0.6)
    assert res.rmse.shape[0] == 500
    assert list(res.p_values.index) == list(range(2, res.rmse.shape[1] + 1))


def test_eigenvalue_rmse_matches_direct_computation() -> None:
    rng = np.random.default_rng(0)
    samples = rng.normal(size=(3, 50, 4))
    observed = np.array([1.5, 1.0, 0.9, 0.6])
    expected = [
        np.sqrt(np.mean((np.linalg.eigvalsh(np.corrcoef(s, rowvar=False))[::-1] - observed) ** 2))
        for s in samples
    ]
    np.testing.assert_allclose(eigenvalue_rmse(samples, observed), expected, rtol=1e-12)


def test_comparison_data_is_reproducible_and_respects_max_factors() -> None:
    data = np.asarray(_cd_case("sim_3f")["data"], dtype=float)
    first = comparison_data(data, rng=5, max_factors=2, n_samples=50)
    second = comparison_data(data, rng=5, max_factors=2, n_samples=50)
    np.testing.assert_array_equal(first.rmse.to_numpy(), second.rmse.to_numpy())
    assert first.max_factors == 2 and first.n_factors == 2
    assert list(first.population_rmse.index) == [1, 2]


@pytest.mark.parametrize(
    ("kwargs", "match"),
    [
        ({"max_factors": 0}, "max_factors"),
        ({"n_population": 1}, "n_population"),
        ({"n_samples": 1}, "n_samples"),
        ({"alpha": 1.0}, "alpha"),
    ],
)
def test_invalid_options(kwargs: dict[str, Any], match: str) -> None:
    data = np.asarray(_cd_case("sim_3f")["data"], dtype=float)
    with pytest.raises(SpecificationError, match=match):
        comparison_data(data, rng=0, **kwargs)


def test_invalid_data() -> None:
    data = np.asarray(_cd_case("sim_3f")["data"], dtype=float)
    missing = data.copy()
    missing[0, 0] = np.nan
    with pytest.raises(SpecificationError, match="complete data"):
        comparison_data(missing, rng=0)
    constant = data.copy()
    constant[:, 1] = 1.0
    with pytest.raises(SpecificationError, match="distinct values"):
        comparison_data(constant, rng=0)
