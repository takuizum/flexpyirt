"""Confirmatory and exploratory DETECT (DESIGN.md §16.13, VALIDATION.md V27).

``tests/reference/v27_detect.json`` is generated by ``validation/r/m5_detect_reference.R`` with
sirt 4.2.133: ``conf.detect(use_sum_score = TRUE, bias_corr = TRUE, smooth = FALSE)`` and
``expl.detect(use_sum_score = TRUE, estsample = ...)``.
"""

from __future__ import annotations

from functools import cache
from typing import Any

import numpy as np
import pandas as pd
import pytest

from flexpyctt import detect, exploratory_detect
from flexpyctt._detect import conditional_covariances, ward_clusters
from flexpyctt.errors import SpecificationError
from reference_data import load_reference

EXACT = 1e-12


@cache
def _reference() -> dict[str, Any]:
    return load_reference("v27_detect")


def _frame(case: dict[str, Any]) -> pd.DataFrame:
    return pd.DataFrame(case["data"], columns=case["items"], dtype=float)


def _partitions() -> list[tuple[str, str]]:
    return [(c["name"], p) for c in _reference()["cases"] for p in c["partitions"]]


@pytest.mark.parametrize(("name", "partition"), _partitions())
def test_detect_matches_sirt(name: str, partition: str) -> None:
    case = next(c for c in _reference()["cases"] if c["name"] == name)
    res = detect(_frame(case), case["partitions"][partition])
    ref = case["results"][partition]
    assert list(res.indices.index) == _reference()["index_names"]
    np.testing.assert_allclose(res.indices["unweighted"], ref["indices"]["unweighted"], atol=EXACT)
    np.testing.assert_allclose(res.indices["weighted"], ref["indices"]["weighted"], atol=EXACT)
    cc = res.conditional_covariance.to_numpy()
    for pair in ref["ccov"]:
        assert cc[pair["i"], pair["j"]] == pytest.approx(pair["ccov"], abs=1e-15)
    assert res.detect == res.indices.loc["DETECT", "unweighted"]
    assert res.assi == res.indices.loc["ASSI", "unweighted"]
    assert res.ratio == res.indices.loc["RATIO", "unweighted"]
    assert res.n_obs == len(case["data"])


def test_detect_separates_structure_from_unidimensionality() -> None:
    cases = {c["name"]: c for c in _reference()["cases"]}
    two = detect(_frame(cases["sim_2d"]), cases["sim_2d"]["partitions"]["true"])
    one = detect(_frame(cases["sim_1d"]), cases["sim_1d"]["partitions"]["halves"])
    assert two.detect > 1.0 and two.assi > 0.25 and two.ratio > 0.36
    assert one.detect < 0.2


def test_exploratory_detect_matches_sirt() -> None:
    ref = _reference()["exploratory"]
    res = exploratory_detect(_frame(ref), max_clusters=4, estimation_rows=ref["estimation_rows"])
    table = res.table.set_index("n_clusters")
    for part in ref["partitions"]:
        k = part["k"]
        assert list(res.clusters[k]) == part["clusters"]
        est = table.loc[k, ["DETECT_estimation", "ASSI_estimation", "RATIO_estimation"]]
        val = table.loc[k, ["DETECT_validation", "ASSI_validation", "RATIO_validation"]]
        np.testing.assert_allclose(est.to_numpy(float), part["estimation"][:3], atol=EXACT)
        np.testing.assert_allclose(val.to_numpy(float), part["validation"][:3], atol=EXACT)
    assert res.n_clusters == 3
    assert list(table["cluster_sizes"]) == ["10-5", "5-5-5", "3-2-5-5"]
    np.testing.assert_array_equal(res.estimation_rows, ref["estimation_rows"])
    assert res.validation_rows.size + res.estimation_rows.size == len(ref["data"])


def test_ward_clusters_reproduce_hclust_ward_d_merge_heights() -> None:
    """R's ward.D heights are SciPy's Ward heights on sqrt(d), squared."""
    from scipy.cluster.hierarchy import linkage

    ref = _reference()["exploratory"]
    x = _frame(ref).to_numpy()[np.asarray(ref["estimation_rows"])]
    ccov = conditional_covariances(x)
    dist = np.max(ccov) - ccov
    tree = linkage(np.sqrt(dist[np.triu_indices(ccov.shape[0], 1)]), method="ward")
    np.testing.assert_allclose(np.sort(tree[:, 2] ** 2), np.sort(ref["merge_heights"]), atol=1e-12)
    assert set(ward_clusters(ccov, [2, 3])) == {2, 3}


def test_exploratory_detect_random_split_is_reproducible() -> None:
    ref = _reference()["exploratory"]
    first = exploratory_detect(_frame(ref), rng=3)
    second = exploratory_detect(_frame(ref), rng=3)
    np.testing.assert_array_equal(first.estimation_rows, second.estimation_rows)
    assert first.estimation_rows.size == len(ref["data"]) // 2
    pd.testing.assert_frame_equal(first.table, second.table)


def test_detect_cluster_inputs() -> None:
    case = _reference()["cases"][0]
    df = _frame(case)
    labels = case["partitions"]["true"]
    as_list = detect(df, labels)
    as_dict = detect(
        df, dict(zip(df.columns, ["a" if v == 1 else "b" for v in labels], strict=True))
    )
    as_series = detect(df, pd.Series(labels, index=df.columns)[::-1])
    for other in (as_dict, as_series):
        pd.testing.assert_frame_equal(as_list.indices, other.indices)
    assert detect(df.to_numpy(), labels).detect == pytest.approx(as_list.detect)


def _with_missing(df: pd.DataFrame) -> pd.DataFrame:
    out = df.copy()
    out.iloc[0, 0] = np.nan
    return out


@pytest.mark.parametrize(
    ("call", "match"),
    [
        (lambda df: detect(df, [1, 2]), "labels for"),
        (lambda df: detect(df, {"x1": 1}), "every item"),
        (lambda df: detect(df.iloc[:, :2], [1, 2]), "at least 3"),
        (lambda df: detect(_with_missing(df), [1] * 6 + [2] * 6), "complete data"),
        (lambda df: exploratory_detect(df, max_clusters=1, rng=0), "max_clusters"),
        (lambda df: exploratory_detect(df), "exactly one"),
        (lambda df: exploratory_detect(df, estimation_rows=[10**6]), "row positions"),
        (lambda df: exploratory_detect(df, estimation_rows=np.arange(len(df))), "validation"),
    ],
)
def test_invalid_inputs(call: Any, match: str) -> None:
    df = _frame(_reference()["cases"][0])
    with pytest.raises(SpecificationError, match=match):
        call(df)
