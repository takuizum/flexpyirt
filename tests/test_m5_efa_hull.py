"""D5: EFA (ULS / ML) and the Hull method (DESIGN.md §16.14, VALIDATION.md V28).

``tests/reference/v28_efa_hull.json`` is generated by ``validation/r/m5_efa_hull_reference.R``:
EFAtools 1.1.0 ``EFA(method = "ULS" / "ML", rotation = "none")`` and ``HULL()`` on the V24
polychoric matrices with at least 6 variables and two simulated Pearson matrices, plus psych's
``fa()`` on one of them.
"""

from __future__ import annotations

import json
import warnings
from functools import cache
from typing import Any

import jax
import numpy as np
import pandas as pd
import pytest

from flexpyirt import dimensionality, efa, hull, polychoric
from flexpyirt._efa import _ml_objective, _uls_objective, hull_select
from flexpyirt.errors import HeywoodWarning, SpecificationError
from tests._reference import REFERENCE_DIR, check_reference_meta


@cache
def _reference() -> dict[str, Any]:
    raw = dict(json.loads((REFERENCE_DIR / "v28_efa_hull.json").read_text()))
    check_reference_meta(raw["meta"])
    return raw


def _efa_cases() -> list[tuple[str, int, str]]:
    return [(c["name"], e["k"], e["method"]) for c in _reference()["cases"] for e in c["efa"]]


def _hull_cases() -> list[tuple[str, str, str]]:
    return [
        (c["name"], h["method"], t["gof"])
        for c in _reference()["cases"]
        for h in c["hull"]
        for t in h["tables"]
    ]


def _case(name: str) -> dict[str, Any]:
    return next(c for c in _reference()["cases"] if c["name"] == name)


def _efa_quiet(corr: np.ndarray, **kwargs: Any) -> Any:
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", HeywoodWarning)
        return efa(corr, **kwargs)


@pytest.mark.parametrize(("name", "k", "method"), _efa_cases())
def test_efa_matches_efatools(name: str, k: int, method: str) -> None:
    case = _case(name)
    ref = next(e for e in case["efa"] if e["k"] == k and e["method"] == method)
    corr = np.asarray(case["correlation"])
    res = _efa_quiet(corr, n_factors=k, method=method.lower(), n_obs=case["n"])
    lam = res.loadings.to_numpy()
    lam_ref = np.asarray(ref["loadings"])
    np.testing.assert_allclose(lam @ lam.T, lam_ref @ lam_ref.T, rtol=0, atol=1e-4)
    np.testing.assert_allclose(res.communalities, ref["h2"], rtol=0, atol=1e-4)
    assert res.fit["df"] == ref["fit"]["df"]
    for key in ("caf", "cfi", "rmsea"):
        assert res.fit[key] == pytest.approx(ref["fit"][key], abs=2e-4), key
    assert res.fit["chi2"] == pytest.approx(ref["fit"]["chi2"], rel=1e-4, abs=1e-3)
    # flexpyirt's optimum is at least as good as EFAtools' (psi = 1 - h2 there).
    fun = _uls_objective if method == "ULS" else _ml_objective
    psi_ref = np.clip(1.0 - np.asarray(ref["h2"]), 0.005, None)
    assert res.objective <= fun(psi_ref, corr, k)[0] + 1e-10


def test_efa_matches_psych_fa() -> None:
    corr = np.asarray(_case("sim_3f")["correlation"])
    for ref in _reference()["psych_sim_3f"]:
        res = efa(corr, n_factors=3, method="uls" if ref["fm"] == "minres" else "ml")
        lam, lam_ref = res.loadings.to_numpy(), np.asarray(ref["loadings"])
        np.testing.assert_allclose(lam @ lam.T, lam_ref @ lam_ref.T, atol=1e-4)
        np.testing.assert_allclose(res.uniquenesses, ref["uniquenesses"], atol=1e-4)
        assert res.converged and not res.heywood


@pytest.mark.parametrize(("name", "method", "gof"), _hull_cases())
def test_hull_matches_efatools(name: str, method: str, gof: str) -> None:
    case = _case(name)
    spec = next(h for h in case["hull"] if h["method"] == method)
    ref = next(t for t in spec["tables"] if t["gof"] == gof)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        res = hull(
            np.asarray(case["correlation"]),
            n_obs=case["n"],
            max_factors=spec["max_factors"],
            method=method.lower(),  # type: ignore[arg-type]
            fit_index=gof.lower(),  # type: ignore[arg-type]
        )
    assert res.n_factors == ref["n_factors"]
    assert list(res.table["on_hull"]) == ref["on_hull"]
    np.testing.assert_array_equal(res.table["df"], ref["df"])
    np.testing.assert_allclose(res.table["fit"], ref["fit"], rtol=0, atol=1e-5)
    st_ref = np.array([np.nan if v is None else v for v in ref["st"]], dtype=float)
    np.testing.assert_array_equal(np.isnan(res.table["st"]), np.isnan(st_ref))
    finite = np.isfinite(st_ref)
    np.testing.assert_allclose(res.table["st"][finite], st_ref[finite], rtol=1e-2)
    assert res.max_factors == spec["max_factors"]


def test_hull_select_rules() -> None:
    # Fit increasing then flat: k = 2 is the elbow.
    fit = np.array([0.0, 0.6, 0.9, 0.92, 0.93])
    df = np.array([28.0, 20.0, 13.0, 7.0, 2.0])
    k, st, on = hull_select(fit, df)
    assert on.all()
    assert k == 2
    assert np.isnan(st[0]) and np.isnan(st[-1])
    # A decreasing fit drops the point; fewer than three on the hull -> best fit.
    k2, st2, on2 = hull_select(np.array([0.0, 0.5, 0.4]), np.array([10.0, 5.0, 1.0]))
    assert k2 == 1 and np.isnan(st2).all() and list(on2) == [True, True, False]


def test_hull_default_bound_from_parallel_analysis() -> None:
    case = _case("sim_3f")
    corr = np.asarray(case["correlation"])
    first = hull(corr, n_obs=case["n"], key=jax.random.key(0), n_replications=200)
    second = hull(corr, n_obs=case["n"], key=jax.random.key(0), n_replications=200)
    assert first.max_factors == second.max_factors == 4
    assert first.n_factors == 3
    assert list(first.table.columns) == [
        "n_factors",
        "fit",
        "df",
        "st",
        "on_hull",
        "heywood",
        "converged",
    ]


def test_efa_without_n_obs_reports_caf_only_and_warns_on_heywood() -> None:
    corr = np.asarray(_case("tetrachoric_sim")["correlation"])
    with pytest.warns(HeywoodWarning):
        res = efa(corr, n_factors=3)
    assert set(res.fit) == {"caf", "df"}
    assert res.heywood


def test_efa_from_polychoric_result_uses_its_n() -> None:
    rng = np.random.default_rng(5)
    z = rng.normal(size=(400, 1))
    data = pd.DataFrame((z + rng.normal(size=(400, 6)) > 0).astype(float), columns=list("abcdef"))
    pc = polychoric(data)
    res = efa(pc, n_factors=1)
    assert {"chi2", "cfi", "rmsea"} <= set(res.fit)
    assert list(res.loadings.index) == list("abcdef")
    assert (res.loadings.to_numpy() > 0).all()


def test_ensemble_includes_hull_with_six_or_more_items() -> None:
    raw = json.loads((REFERENCE_DIR / "v27_detect.json").read_text())
    case = raw["cases"][0]
    data = pd.DataFrame(case["data"], columns=case["items"], dtype=float)
    res = dimensionality(data, key=jax.random.key(4), n_replications=10)
    row = res.number_of_dimensions.set_index("method").loc["Hull (CAF, ULS)"]
    expected = hull(polychoric(data), key=jax.random.split(jax.random.key(4), 4)[3])
    assert row["n_factors"] == expected.n_factors == 2
    assert res.results["hull"] is not None


@pytest.mark.parametrize(
    ("call", "match"),
    [
        (lambda c: efa(c, n_factors=1, method="pa"), "method"),  # type: ignore[arg-type]
        (lambda c: efa(c, n_factors=0), "n_factors"),
        (lambda c: efa(c, n_factors=5), "n_factors"),
        (lambda c: hull(c[:5, :5], n_obs=100, max_factors=2), "at least 6"),
        (lambda c: hull(c, max_factors=2, fit_index="cfi"), "n_obs"),
        (lambda c: hull(c, n_obs=100), "key"),
        (lambda c: hull(c, n_obs=100, max_factors=9), "max_factors"),
        (lambda c: hull(c, n_obs=100, max_factors=2, fit_index="tli"), "fit_index"),  # type: ignore[arg-type]
    ],
)
def test_invalid_inputs(call: Any, match: str) -> None:
    corr = np.asarray(_case("tetrachoric_sim")["correlation"])
    with pytest.raises(SpecificationError, match=match):
        call(corr)


def test_not_positive_definite_is_rejected() -> None:
    bad = np.full((6, 6), 0.5)
    np.fill_diagonal(bad, 1.0)
    bad[0, 1] = bad[1, 0] = -0.9
    bad[0, 2] = bad[2, 0] = 0.95
    with pytest.raises(SpecificationError, match="positive definite"):
        efa(bad, n_factors=1)
    with pytest.raises(SpecificationError, match="positive definite"):
        hull(bad, n_obs=100, max_factors=2)
