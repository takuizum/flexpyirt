"""V26 (M7): local dependence beyond single-group unidimensional Normal models vs R mirt.

``tests/reference/v26_local_dependence_extensions.json`` is generated by
``validation/r/m7_local_dependence_reference.R`` (mirt 1.48): ``residuals(type = "LD" / "LDG2" /
"Q3")`` on ``multipleGroup`` fits (one and two factors), ``dentype = "EH"`` and
``"Davidian-2"`` fits with the fitted density (``use_dentype_estimate = TRUE``;
``Theta = fscores(m, use_dentype_estimate = TRUE)`` for Q3), a normal-mixture density put into a
single-group mirt object (mirt has no ``residuals()`` for mixtures), and ``mirt.model`` fits with
two and three factors.

mirt's estimates are put into a flexpyirt ``FitResult`` with every parameter fixed, so the
comparison is of the statistics alone and does not depend on how tightly either program
converged (the estimates themselves are compared in V4, V6, V14, V19, V21 and V22).
"""

from __future__ import annotations

import json
import warnings
from dataclasses import replace
from functools import cache
from typing import Any

import numpy as np
import pandas as pd
import pytest

from flexpyirt import (
    BAEM,
    GRM,
    DavidianCurve,
    EmpiricalHistogram,
    FitResult,
    Model,
    Normal,
    NormalMixture,
    Quadrature,
    TwoPL,
    fit,
)
from flexpyirt._compile import LATENT_ITEM
from tests._reference import REFERENCE_DIR, check_reference_meta

# mirt reference comparison: nightly and release-PR CI only (CONTRIBUTING.md, "Tests").
pytestmark = pytest.mark.slow

CASES = [
    "groups_2pl",
    "groups_grm",
    "eh_2pl",
    "davidian_2pl",
    "mixture_2pl",
    "factors2_2pl",
    "factors2_grm",
    "factors3_2pl",
    "groups_factors2_2pl",
]
TOL_LOGLIK_REL = 1e-9
TOL_STAT_REL = 1e-7
TOL_V_Q3_ABS = 1e-8


@cache
def _reference() -> dict[str, Any]:
    raw = dict(json.loads((REFERENCE_DIR / "v26_local_dependence_extensions.json").read_text()))
    check_reference_meta(raw["meta"], require_grid_check=True)
    return raw


def _case(name: str) -> dict[str, Any]:
    return next(c for c in _reference()["cases"] if c["name"] == name)


def _data(case: dict[str, Any]) -> tuple[pd.DataFrame, np.ndarray | None]:
    if "data_from" in case:
        src = json.loads((REFERENCE_DIR / f"{case['data_from']}.json").read_text())
        pats = pd.DataFrame(np.asarray(src["patterns"], dtype=float), columns=case["items"])
        return pats.loc[pats.index.repeat(src["counts"])].reset_index(drop=True), None
    rows = [[np.nan if v is None else v for v in row] for row in case["data"]]
    group = None if case["group"] is None else np.asarray(case["group"])
    return pd.DataFrame(rows, columns=case["items"], dtype=float), group


def _spec(case: dict[str, Any], df: pd.DataFrame) -> Model:
    kernel = TwoPL() if case["itemtype"] == "2PL" else GRM(int(np.nanmax(df.to_numpy())) + 1)
    spec = Model.uniform(kernel, items=case["items"])
    if case["factors"] is not None:
        spec = spec.with_factors(case["factors"])
    kind, first = case["kind"], case["groups"][0]
    if kind == "groups":
        # mirt orders the groups alphabetically, so "focal" is its N(0, 1) reference group.
        spec = spec.with_groups(focal=Normal.standard(), ref=Normal.free())
        spec = spec.equal_across_groups(items=case["anchors"])
    elif kind == "eh":
        spec = spec.with_latent(EmpiricalHistogram())
    elif kind == "davidian":
        spec = spec.with_latent(DavidianCurve(int(first["degree"])))
    elif kind == "mixture":
        spec = spec.with_latent(NormalMixture(int(first["n_components"])))
    return spec


def _latent_values(case: dict[str, Any], block: dict[str, Any]) -> dict[str, float]:
    if case["kind"] == "davidian":
        dav = block["davidian"]
        phi = {f"phi_{k}": float(v) for k, v in enumerate(dav["phi"], start=1)}
        return {"mean": float(dav["mean"]), "var": float(dav["var"]), **phi}
    if case["kind"] == "mixture":
        return {k: float(v) for k, v in block["mixture"].items()}
    return {k: float(v) for k, v in (block["latent"] or {}).items()}


@cache
def _at_mirt(name: str) -> FitResult:
    """A FitResult holding mirt's estimates, every parameter fixed (no estimation)."""
    case = _case(name)
    df, group = _data(case)
    spec = _spec(case, df)
    table = spec.parameter_table(df, group=group)
    blocks = {b["group"]: b for b in case["groups"]}
    unidimensional = case["factors"] is None
    for idx, row in table.iterrows():
        block = blocks[row["group"]] if case["kind"] == "groups" else case["groups"][0]
        if row["item"] == LATENT_ITEM:
            values = _latent_values(case, block)
            if row["param"] in values:
                table.at[idx, "value"] = values[row["param"]]
            continue
        source = block["items"][row["item"]]
        key = "a1" if unidimensional and row["param"] == "a" else row["param"]
        table.at[idx, "value"] = float(source[key])
    table["free"] = False
    table["free_id"] = -1
    quad = Quadrature.equispaced(int(case["quadpts"]), bounds=(-6, 6))
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")  # the histogram is replaced below, not estimated
        res = fit(
            spec, df, group=group, table=table, quadrature=quad, se=None, method=BAEM(max_iter=1)
        )
    if case["kind"] == "eh":
        res = replace(res, _eh_weights=np.asarray(case["groups"][0]["prior"])[None, :])
    return res


def _pairs(name: str) -> tuple[pd.DataFrame, pd.DataFrame]:
    """flexpyirt's and mirt's pair tables, one row per (group, pair), in the same order."""
    case = _case(name)
    df, group = _data(case)
    ld = _at_mirt(name).local_dependence(df, group=group)
    index = {item: k for k, item in enumerate(case["items"])}
    got = ld.pairs.assign(i=ld.pairs["item_i"].map(index), j=ld.pairs["item_j"].map(index))
    if "group" not in got:
        got.insert(0, "group", "all")
    frames = [pd.DataFrame(b["pairs"]).assign(group=b["group"] or "all") for b in case["groups"]]
    ref = pd.concat(frames, ignore_index=True)
    keys = ["group", "i", "j"]
    return (
        got.sort_values(keys).reset_index(drop=True),
        ref.sort_values(keys).reset_index(drop=True),
    )


@pytest.mark.parametrize("name", [c for c in CASES if c not in ("eh_2pl", "mixture_2pl")])
def test_loglik_at_mirt_estimates(name: str) -> None:
    """The parameters were mapped correctly: the log-likelihood is mirt's."""
    assert _at_mirt(name).loglik == pytest.approx(_case(name)["loglik"], rel=TOL_LOGLIK_REL)


@pytest.mark.parametrize("name", ["eh_2pl", "davidian_2pl", "mixture_2pl"])
def test_grid_weights_are_the_reference_density(name: str) -> None:
    case = _case(name)
    df, _ = _data(case)
    res = _at_mirt(name)
    prior = np.asarray(case["groups"][0]["prior"])
    # The EAP posterior is proportional to likelihood x weights; with a flat likelihood (all
    # responses missing) the EAP is the mean of the weights.
    blank = pd.DataFrame(np.full((1, df.shape[1]), np.nan), columns=df.columns)
    nodes = np.linspace(-6, 6, prior.size)
    assert float(res.score(blank)["theta"].iloc[0]) == pytest.approx(
        float(prior @ nodes), abs=1e-10
    )


@pytest.mark.parametrize("name", CASES)
def test_local_dependence_matches_mirt(name: str) -> None:
    got, ref = _pairs(name)
    assert len(got) == len(ref)
    assert list(got["group"]) == list(ref["group"])
    assert list(got["i"]) == list(ref["i"])
    assert list(got["j"]) == list(ref["j"])
    np.testing.assert_allclose(got["x2"], ref["x2"], rtol=TOL_STAT_REL)
    np.testing.assert_allclose(got["g2"], ref["g2"], rtol=TOL_STAT_REL)
    np.testing.assert_allclose(got["cramer_v"], ref["cramer_v"], rtol=0, atol=TOL_V_Q3_ABS)
    np.testing.assert_allclose(got["q3"], ref["q3"], rtol=0, atol=TOL_V_Q3_ABS)


@pytest.mark.parametrize(
    ("name", "bound"), [("factors2_2pl", 1e-8), ("factors2_grm", 1e-8), ("factors3_2pl", 5e-4)]
)
def test_q3_grid_effect_of_mirt_default_scores(name: str, bound: float) -> None:
    """mirt's default Q3 scores on 61 / 31 points per dimension, the fits used 31 / 15."""
    got, ref = _pairs(name)
    assert float(np.max(np.abs(got["q3"] - ref["q3_default"]))) < bound


@pytest.mark.parametrize("name", ["groups_2pl", "groups_factors2_2pl"])
def test_group_columns_and_q3_star(name: str) -> None:
    case = _case(name)
    df, group = _data(case)
    ld = _at_mirt(name).local_dependence(df, group=group)
    n_pairs = len(case["items"]) * (len(case["items"]) - 1) // 2
    assert list(ld.pairs.columns[:3]) == ["group", "item_i", "item_j"]
    assert list(ld.pairs["group"].unique()) == ["focal", "ref"]
    assert len(ld.pairs) == 2 * n_pairs
    assert isinstance(ld.q3_mean, pd.Series)
    for g in ("ref", "focal"):
        sub = ld.pairs[ld.pairs["group"] == g]
        assert ld.q3_mean[g] == pytest.approx(float(sub["q3"].mean()))
        np.testing.assert_allclose(sub["q3_star"], sub["q3"] - ld.q3_mean[g])
        mat = ld.q3.loc[g]
        assert list(mat.index) == case["items"]
        np.testing.assert_allclose(
            mat.to_numpy()[np.triu_indices(len(case["items"]), 1)], sub["q3"]
        )
    assert ld.max_q3_star == pytest.approx(float(ld.pairs["q3_star"].max()))


def test_refit_agrees_with_mirt_for_two_groups() -> None:
    """End to end: flexpyirt's own two-group fit gives mirt's statistics."""
    case = _case("groups_2pl")
    df, group = _data(case)
    res = fit(
        _spec(case, df),
        df,
        group=group,
        method=BAEM(tol=1e-9, max_iter=20000),
        quadrature=Quadrature.equispaced(int(case["quadpts"]), bounds=(-6, 6)),
        se=None,
    )
    assert res.loglik >= case["loglik"] - 1e-6 * abs(case["loglik"])
    ld = res.local_dependence(df, group=group)
    _, ref = _pairs("groups_2pl")
    index = {item: k for k, item in enumerate(case["items"])}
    got = ld.pairs.assign(i=ld.pairs["item_i"].map(index), j=ld.pairs["item_j"].map(index))
    got = got.sort_values(["group", "i", "j"]).reset_index(drop=True)
    # mirt was fitted to TOL = 1e-6; observed 4e-4 (X2, G2) and 5e-6 (V, Q3).
    np.testing.assert_allclose(got["x2"], ref["x2"], rtol=0, atol=2e-3)
    np.testing.assert_allclose(got["g2"], ref["g2"], rtol=0, atol=2e-3)
    np.testing.assert_allclose(got["cramer_v"], ref["cramer_v"], rtol=0, atol=5e-5)
    np.testing.assert_allclose(got["q3"], ref["q3"], rtol=0, atol=5e-5)
