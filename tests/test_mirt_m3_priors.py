"""Numerical agreement with R mirt / exact R MAP for M3 priors (VALIDATION.md V7).

Reference files are generated by ``validation/r/m3_priors_reference.R`` on 61 equally spaced
points on [-6, 6]:

- ``v7_2pl_map``: 2PL (J=15, N=1000) with ``a ~ NormalPrior(1.2, 0.5)``,
  ``d ~ NormalPrior(0, 2)``. Fitted directly with R mirt (``optimizer = "NR"``, ``TOL = 1e-10``):
  parameters, log-likelihood, log-posterior, and Oakes SEs all match mirt directly.
- ``v7_2pl_lnorm_map``: 2PL (J=15, N=1000) with ``a ~ LogNormal(0.2, 0.3)``,
  ``d ~ NormalPrior(0, 2)``. Fitted directly with R mirt (``optimizer = "NR"``): parameters,
  log-likelihood and log-posterior match mirt directly; posterior SEs are checked against the
  exact R posterior Hessian (mirt 1.46's ``DerivativePriors`` has a sign bug in the ``lnorm``
  Hessian).
- ``v7_3pl_map``: 3PL (J=15, N=1000) with ``a ~ LogNormal(0.2, 0.3)``,
  ``d ~ NormalPrior(0, 2)``, ``g ~ Beta(5, 17)`` (``expbeta`` in mirt, natural scale without
  Jacobian). Maximizes mirt's exact ``logLik + logPrior`` objective in R (cross-checked via mirt
  with fixed parameters to ~1e-14, plus EAP from mirt ``fscores``), because mirt 1.46's
  ``DerivativePriors`` omits the logit chain-rule factor ``g*(1-g)`` for ``expbeta``.

For ``v7_2pl_map`` and ``v7_2pl_lnorm_map``, we also confirm that mirt's
``SE.type = "Richardson"`` (which uses ``BL.LL`` without ``LL.Priors``) matches flexpyirt's
likelihood-only Hessian evaluated at the MAP estimate.
"""

from __future__ import annotations

import json
import warnings
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any

import jax.numpy as jnp
import numpy as np
import pandas as pd
import pytest

from flexpyirt import (
    BAEM,
    Beta,
    FitResult,
    LogNormal,
    Model,
    NormalPrior,
    Quadrature,
    ThreePL,
    TwoPL,
    _core,
    fit,
)
from flexpyirt._compile import compile_problem, prepare
from flexpyirt.errors import HeywoodWarning
from flexpyirt.priors import Prior
from tests._reference import check_reference_meta

REFERENCE_DIR = Path(__file__).parent / "reference"
SQUAREM = (False, True)
TOL_LOGLIK_REL = 1e-6
TOL_PARAM = 1e-4
TOL_SE_REL = 1e-3
TOL_EAP = 1e-5
CASES = ["v7_2pl_map", "v7_2pl_lnorm_map", "v7_3pl_map"]


def _build_prior(spec: dict[str, Any]) -> Prior:
    dist = spec["dist"]
    if dist == "NormalPrior":
        return NormalPrior(mean=float(spec["mean"]), sd=float(spec["sd"]))
    if dist == "LogNormal":
        return LogNormal(meanlog=float(spec["meanlog"]), sdlog=float(spec["sdlog"]))
    if dist == "Beta":
        return Beta(a=float(spec["a"]), b=float(spec["b"]))
    raise ValueError(f"Unknown prior spec {spec!r}")


@dataclass(frozen=True)
class Case:
    name: str
    raw: dict[str, Any]
    spec: Model
    quadrature: Quadrature

    @property
    def patterns(self) -> pd.DataFrame:
        return pd.DataFrame(
            np.asarray(self.raw["patterns"], dtype=float), columns=self.raw["items"]
        )

    @property
    def counts(self) -> np.ndarray:
        return np.asarray(self.raw["counts"], dtype=int)

    @property
    def data(self) -> pd.DataFrame:
        return self.patterns.loc[self.patterns.index.repeat(self.counts)].reset_index(drop=True)

    @property
    def param_names(self) -> tuple[str, ...]:
        return ("a", "d", "g", "u") if self.raw["meta"]["itemtype"] == "3PL" else ("a", "d")

    def params(self, key: str = "estimates") -> pd.DataFrame:
        rows = self.raw[key]["all"]["params"]
        frame: pd.DataFrame = pd.DataFrame(rows).T
        return frame.loc[list(self.raw["items"])]


@cache
def load(name: str) -> Case:
    raw = dict(json.loads((REFERENCE_DIR / f"{name}.json").read_text()))
    require_rich = name != "v7_3pl_map"
    check_reference_meta(raw["meta"], require_richardson=require_rich, require_grid_check=True)
    items = raw["items"]
    item_model = ThreePL() if raw["meta"]["itemtype"] == "3PL" else TwoPL()
    spec = Model.uniform(item_model, items=items)
    for param, pspec in raw["priors"].items():
        spec = spec.prior(param=param, dist=_build_prior(pspec))
    return Case(name, raw, spec, Quadrature.equispaced())


@cache
def _fit(name: str, se: str, squarem: bool = False) -> FitResult:
    case = load(name)
    with warnings.catch_warnings():
        warnings.simplefilter("error", HeywoodWarning)
        return fit(
            case.spec,
            case.data,
            method=BAEM(tol=1e-9, max_iter=20000, squarem=squarem),
            quadrature=case.quadrature,
            se=se,  # type: ignore[arg-type]
        )


@cache
def _fixed_at_reference(name: str) -> FitResult:
    """All parameters fixed at the reference estimates (for likelihood and EAP checks)."""
    case = load(name)
    table = case.spec.parameter_table(case.data)
    est = case.raw["estimates"]["all"]
    values = [
        est["latent"][param] if item == "__latent__" else est["params"][item][param]
        for item, param in zip(table["item"], table["param"], strict=True)
    ]
    table["value"] = np.asarray(values, dtype=float)
    table["free"] = False
    return fit(case.spec, case.data, table=table, quadrature=case.quadrature, se=None)


def _log_posterior_at_reference(name: str) -> float:
    """Evaluate flexpyirt's log posterior at the reference estimates (with parameters free)."""
    case = load(name)
    table = case.spec.parameter_table(case.data)
    est = case.raw["estimates"]["all"]
    values = [
        est["latent"][param] if item == "__latent__" else est["params"][item][param]
        for item, param in zip(table["item"], table["param"], strict=True)
    ]
    table["value"] = np.asarray(values, dtype=float)
    prep = prepare(case.spec, case.data, group=None, item_names=None, table=table)
    comp = compile_problem(case.spec, prep.y, prep.group, prep.table, case.quadrature)
    return float(_core.log_posterior(comp.problem, jnp.asarray(comp.eta0)))


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_loglik_and_log_posterior(name: str, squarem: bool) -> None:
    case, res = load(name), _fit(name, "oakes", squarem)
    assert res.converged
    ref_ll = float(case.raw["loglik"])
    ref_lp = float(case.raw["log_posterior"])
    assert abs(res.loglik - ref_ll) <= TOL_LOGLIK_REL * abs(ref_ll)
    assert abs(res.log_posterior - ref_lp) <= TOL_LOGLIK_REL * abs(ref_lp)
    assert _fixed_at_reference(name).loglik == pytest.approx(ref_ll, rel=1e-12)
    assert res.log_posterior >= _log_posterior_at_reference(name) - 1e-8
    if name == "v7_3pl_map":
        # mirt 1.46's BFGS stops at a strictly lower log-posterior due to its expbeta gradient bug.
        mirt_bfgs_lp = float(case.raw["meta"]["mirt_bfgs_diagnostic"]["log_posterior"])
        assert res.log_posterior > mirt_bfgs_lp + 1.0


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_parameters(name: str, squarem: bool) -> None:
    case, res = load(name), _fit(name, "oakes", squarem)
    ref = case.params()
    ours = res.items.set_index("item").loc[ref.index]
    for p in case.param_names:
        np.testing.assert_allclose(ours[p], ref[p].astype(float), rtol=0, atol=TOL_PARAM)


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize(
    ("name", "se", "key"),
    [
        # Direct mirt Oakes SE agreement (norm priors have exact derivatives in mirt 1.46).
        ("v7_2pl_map", "oakes", "estimates"),
        ("v7_2pl_map", "hessian", "se_posterior_exact"),
        # Exact R posterior Hessian SEs for lnorm and 3PL+Beta cases.
        ("v7_2pl_lnorm_map", "oakes", "se_posterior_exact"),
        ("v7_2pl_lnorm_map", "hessian", "se_posterior_exact"),
        ("v7_3pl_map", "oakes", "se_posterior_exact"),
        ("v7_3pl_map", "hessian", "se_posterior_exact"),
    ],
)
def test_standard_errors(name: str, se: str, key: str, squarem: bool) -> None:
    case, res = load(name), _fit(name, se, squarem)
    ref = case.params(key)
    ours = res.items.set_index("item").loc[ref.index]
    for p in case.param_names:
        col = f"{p}_se"
        expected = ref[col].astype(float).to_numpy()
        got = ours[col].to_numpy()
        free = np.isfinite(expected)
        np.testing.assert_allclose(got[free], expected[free], rtol=TOL_SE_REL)
        assert np.isnan(got[~free]).all()


@pytest.mark.parametrize("name", ["v7_2pl_map", "v7_2pl_lnorm_map"])
def test_mirt_richardson_matches_likelihood_only_hessian_at_map(name: str) -> None:
    """Confirm mirt's SE.type='Richardson' (BL.LL) omits priors and matches -H_lik(eta_MAP)^-1."""
    case = load(name)
    res = _fit(name, "oakes", False)
    # Build the same problem WITHOUT priors and evaluate -nabla^2 loglik at the MAP estimate.
    spec_noprior = Model.uniform(TwoPL(), items=case.spec.item_names)
    table = spec_noprior.parameter_table(case.data)
    prep = prepare(spec_noprior, case.data, group=None, item_names=None, table=table)
    comp = compile_problem(spec_noprior, prep.y, prep.group, prep.table, case.quadrature)
    info_lik = np.asarray(_core.information_hessian(comp.problem, jnp.asarray(res._eta)))
    se_lik = np.sqrt(np.diag(np.linalg.inv(info_lik)))

    # Map free_id order back to (item, param) and compare against mirt's Richardson SEs.
    free_rows = prep.table[prep.table["free"]].copy()
    free_rows["se_lik"] = se_lik[free_rows["free_id"].to_numpy()]
    ours_lik = free_rows.pivot(index="item", columns="param", values="se_lik").loc[
        case.raw["items"]
    ]
    ref_rich = case.params("se_richardson")
    for p in ("a", "d"):
        np.testing.assert_allclose(
            ours_lik[p].to_numpy(),
            ref_rich[f"{p}_se"].astype(float).to_numpy(),
            rtol=TOL_SE_REL,
        )


@pytest.mark.parametrize("name", CASES)
def test_eap_with_mirt_parameters(name: str) -> None:
    case = load(name)
    scores = _fixed_at_reference(name).score(case.patterns)
    np.testing.assert_allclose(scores["theta"], case.raw["eap"]["theta"], rtol=0, atol=TOL_EAP)
    np.testing.assert_allclose(scores["se"], case.raw["eap"]["se"], rtol=0, atol=TOL_EAP)


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_em_monotone(name: str, squarem: bool) -> None:
    res = _fit(name, "oakes", squarem)
    lp = res.history["log_posterior"].to_numpy()
    assert np.all(np.diff(lp) >= -1e-9 * np.abs(lp[1:]))
    assert res.log_posterior >= lp[-1] - 1e-9 * abs(lp[-1])


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_oakes_equals_hessian(name: str, squarem: bool) -> None:
    oakes, hess = _fit(name, "oakes", squarem), _fit(name, "hessian", squarem)
    assert oakes.vcov is not None and hess.vcov is not None
    np.testing.assert_allclose(oakes.vcov, hess.vcov, rtol=1e-6, atol=1e-12)
