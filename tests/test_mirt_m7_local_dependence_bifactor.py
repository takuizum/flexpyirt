"""V38 (M7): local dependence for bifactor and two-tier models vs R mirt (DESIGN.md §17.3).

``tests/reference/v38_local_dependence_bifactor.json`` is generated by
``validation/r/m7_local_dependence_bifactor_reference.R`` (mirt 1.48): ``residuals(type = "LD" /
"LDG2" / "Q3")`` on ``bfactor()`` fits (a bifactor 2PL with general-only items and missing data,
a bifactor GRM, and a two-tier 2PL from ``bfactor(model2 = )``). mirt sums the expected tables
over the full product grid; flexpyirt over the reduced grids.

mirt's estimates are put into a flexpyirt ``FitResult`` with every parameter fixed, so the
comparison is of the statistics alone and does not depend on how tightly either program
converged (the estimates themselves are compared in V32 and V33).
"""

from __future__ import annotations

import json
import warnings
from functools import cache
from typing import Any

import numpy as np
import pandas as pd
import pytest

from flexpyirt import BAEM, GRM, FitResult, Model, Quadrature, TwoPL, fit
from flexpyirt._compile import LATENT_ITEM
from tests._reference import REFERENCE_DIR, check_reference_meta

CASES = ["bifactor_2pl", "bifactor_grm", "two_tier_2pl"]
TOL_LOGLIK_REL = 1e-9
TOL_STAT_REL = 1e-7
TOL_V_Q3_ABS = 1e-8


@cache
def _reference() -> dict[str, Any]:
    raw = dict(json.loads((REFERENCE_DIR / "v38_local_dependence_bifactor.json").read_text()))
    check_reference_meta(raw["meta"], require_grid_check=True)
    return raw


def _case(name: str) -> dict[str, Any]:
    return next(c for c in _reference()["cases"] if c["name"] == name)


def _data(case: dict[str, Any]) -> pd.DataFrame:
    rows = [[np.nan if v is None else v for v in row] for row in case["data"]]
    return pd.DataFrame(rows, columns=case["items"], dtype=float)


def _spec(case: dict[str, Any], df: pd.DataFrame) -> Model:
    kernel = TwoPL() if case["itemtype"] == "2PL" else GRM(int(np.nanmax(df.to_numpy())) + 1)
    spec = Model.uniform(kernel, items=case["items"])
    if case["kind"] == "bifactor":
        return spec.with_bifactor(specific=case["specific"], general="G")
    return spec.with_two_tier(primary=case["primary"], specific=case["specific"])


@cache
def _at_mirt(name: str) -> FitResult:
    """A FitResult holding mirt's estimates, every parameter fixed (no estimation)."""
    case = _case(name)
    df = _data(case)
    spec = _spec(case, df)
    table = spec.parameter_table(df)
    block = case["groups"][0]
    for idx, row in table.iterrows():
        source = block["latent"] if row["item"] == LATENT_ITEM else block["items"][row["item"]]
        table.at[idx, "value"] = float(source[row["param"]])
    table["free"] = False
    table["free_id"] = -1
    quad = Quadrature.equispaced(int(case["quadpts"]), bounds=(-6, 6))
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")  # nothing is estimated
        return fit(spec, df, table=table, quadrature=quad, se=None, method=BAEM(max_iter=1))


def _pairs(name: str) -> tuple[pd.DataFrame, pd.DataFrame]:
    """flexpyirt's and mirt's pair tables, one row per pair, in the same order."""
    case = _case(name)
    ld = _at_mirt(name).local_dependence(_data(case))
    index = {item: k for k, item in enumerate(case["items"])}
    got = ld.pairs.assign(i=ld.pairs["item_i"].map(index), j=ld.pairs["item_j"].map(index))
    ref = pd.DataFrame(case["groups"][0]["pairs"])
    keys = ["i", "j"]
    return (
        got.sort_values(keys).reset_index(drop=True),
        ref.sort_values(keys).reset_index(drop=True),
    )


@pytest.mark.parametrize("name", CASES)
def test_loglik_at_mirt_estimates(name: str) -> None:
    """The parameters were mapped correctly: the log-likelihood is mirt's."""
    assert _at_mirt(name).loglik == pytest.approx(_case(name)["loglik"], rel=TOL_LOGLIK_REL)


@pytest.mark.parametrize("name", CASES)
def test_local_dependence_matches_mirt(name: str) -> None:
    got, ref = _pairs(name)
    assert len(got) == len(ref)
    assert list(got["i"]) == list(ref["i"])
    assert list(got["j"]) == list(ref["j"])
    np.testing.assert_allclose(got["x2"], ref["x2"], rtol=TOL_STAT_REL)
    np.testing.assert_allclose(got["g2"], ref["g2"], rtol=TOL_STAT_REL)
    np.testing.assert_allclose(got["cramer_v"], ref["cramer_v"], rtol=0, atol=TOL_V_Q3_ABS)
    np.testing.assert_allclose(got["q3"], ref["q3"], rtol=0, atol=TOL_V_Q3_ABS)


@pytest.mark.parametrize(
    ("name", "bound"), [("bifactor_2pl", 1e-5), ("bifactor_grm", 1e-7), ("two_tier_2pl", 5e-4)]
)
def test_q3_grid_effect_of_mirt_default_scores(name: str, bound: float) -> None:
    """mirt's default Q3 scores on ``fscores()``'s own grid, not the 21 / 15 points of the fit.

    Observed 2.3e-6, 1.2e-8 and 2.2e-4.
    """
    got, ref = _pairs(name)
    assert float(np.max(np.abs(got["q3"] - ref["q3_default"]))) < bound
