"""Numerical agreement with R mirt's ``pirt()`` (VALIDATION.md V61, DESIGN.md §32).

Reference file ``tests/reference/v61_projection.json`` is generated by
``validation/r/v61_projection_reference.R``: ``bfactor()`` with the V32 settings (``TOL = 1e-10``,
Oakes SEs, 31 points per dimension on ``[-6, 6]``), then ``pirt(estimator = "MML")`` (estimates
and SEs), ``"LKA"`` and ``"FA"`` (with delta-method SEs). The projections are compared both at
flexpyirt's own parent fit (end to end) and at a parent fixed at mirt's estimates (the projection
alone; its covariance is not mirt's, so delta-method SEs are compared end to end only).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import pytest

from flexpyirt import BAEM, GRM, FitResult, Model, Quadrature, TwoPL, fit, project
from tests._reference import check_reference_meta

pytestmark = pytest.mark.slow

REFERENCE_FILE = Path(__file__).parent / "reference" / "v61_projection.json"
CASES = ["bifactor_2pl", "bifactor_grm"]
TOL_PARAM = 1e-4
"""End to end: the parent estimates agree with mirt's to about 1e-5 (V32)."""
TOL_PARAM_FIXED = 2e-5
"""At mirt's parent estimates. The closed forms agree to ~1e-8; MML differs by up to ~5e-6
because mirt keeps the E-table of its last E-step, taken one EM iteration before convergence,
while flexpyirt runs the E-step at the estimates (DESIGN.md §32.3)."""
TOL_SE_REL = 2e-3
KEYS = {"MML": "mml", "logistic_kernel": "lka", "normal_ogive": "fa"}
"""Reference entry of each method (mirt ``estimator = "MML" / "LKA" / "FA"``)."""
Ref = tuple[float, float | None]


@dataclass(frozen=True)
class Case:
    name: str
    raw: dict[str, Any]
    spec: Model
    quadrature: Quadrature

    @property
    def data(self) -> pd.DataFrame:
        patterns = pd.DataFrame(
            np.asarray(self.raw["patterns"], dtype=float), columns=self.raw["items"]
        )
        counts = np.asarray(self.raw["counts"], dtype=int)
        return patterns.loc[patterns.index.repeat(counts)].reset_index(drop=True)


@cache
def load(name: str) -> Case:
    bundle = json.loads(REFERENCE_FILE.read_text())
    check_reference_meta(bundle["meta"], require_grid_check=True)
    raw = dict(bundle["cases"][name])
    meta = raw["meta"]
    check_reference_meta(meta, require_grid_check=True)
    item_model = GRM(int(meta["n_cat"])) if meta["itemtype"] == "graded" else TwoPL()
    specific = {k: list(v) for k, v in raw["specific"].items()}
    spec = Model.uniform(item_model, items=raw["items"]).with_bifactor(specific=specific)
    lo, hi = meta["theta_lim"]
    quad = Quadrature.equispaced(int(meta["quadpts"]), bounds=(float(lo), float(hi)))
    return Case(name=name, raw=raw, spec=spec, quadrature=quad)


@cache
def parent_fit(name: str) -> FitResult:
    case = load(name)
    return fit(
        case.spec,
        case.data,
        method=BAEM(tol=1e-9, max_iter=20000),
        quadrature=case.quadrature,
    )


@cache
def parent_at_mirt(name: str) -> FitResult:
    """The parent with every parameter fixed at mirt's estimates."""
    case = load(name)
    table = case.spec.parameter_table(case.data)
    params = case.raw["parent"]["params"]
    table["value"] = [
        float(v) if item == "__latent__" else float(params[item][param])
        for item, param, v in zip(table["item"], table["param"], table["value"], strict=True)
    ]
    table["free"] = False
    table["free_id"] = -1
    return fit(case.spec, case.data, table=table, quadrature=case.quadrature, se=None)


def _projected(result: FitResult) -> dict[tuple[str, str], tuple[float, float]]:
    rows = result.parameters[result.parameters["item"] != "__latent__"]
    columns = zip(rows["item"], rows["param"], rows["estimate"], rows["se"], strict=True)
    return {(str(i), str(p)): (float(e), float(s)) for i, p, e, s in columns}


def _reference(case: Case, key: str, se: str | None = None) -> dict[tuple[str, str], Ref]:
    """mirt's estimates and SEs of one projection (``se``: which MML SE type)."""
    out: dict[tuple[str, str], Ref] = {}
    for item, entry in case.raw[key].items():
        ses = entry.get("se")
        if ses is not None and key == "mml":
            ses = ses[se or "oakes"]
        for param, value in entry["estimate"].items():
            out[(item, param)] = (float(value), None if ses is None else float(ses[param]))
    return out


@pytest.mark.parametrize("name", CASES)
def test_parent_matches_mirt(name: str) -> None:
    case = load(name)
    result = parent_fit(name)
    assert result.loglik == pytest.approx(case.raw["parent"]["loglik"], rel=1e-8)


@pytest.mark.parametrize("name", CASES)
@pytest.mark.parametrize("method", ["MML", "logistic_kernel", "normal_ogive"])
def test_projection_at_mirt_estimates(name: str, method: str) -> None:
    """The projection alone: the parent is fixed at mirt's estimates."""
    case = load(name)
    ours = _projected(project(parent_at_mirt(name), case.data, method=method))  # type: ignore[arg-type]
    ref = _reference(case, KEYS[method], se="oakes")
    assert set(ours) == set(ref)
    for k, (value, se) in ref.items():
        assert ours[k][0] == pytest.approx(value, abs=TOL_PARAM_FIXED), k
        if method == "MML":
            assert ours[k][1] == pytest.approx(se, rel=TOL_SE_REL), k


@pytest.mark.parametrize("name", CASES)
@pytest.mark.parametrize("se", ["complete", "hessian"])
def test_mml_standard_errors_at_mirt_estimates(name: str, se: str) -> None:
    case = load(name)
    result = project(parent_at_mirt(name), case.data, se=se)  # type: ignore[arg-type]
    ours = _projected(result)
    assert result.se_method == f"projection_{se}"
    for k, (_, ref_se) in _reference(case, "mml", se=se).items():
        assert ours[k][1] == pytest.approx(ref_se, rel=TOL_SE_REL), k


@pytest.mark.parametrize("name", CASES)
@pytest.mark.parametrize("method", ["MML", "logistic_kernel", "normal_ogive"])
def test_projection_end_to_end(name: str, method: str) -> None:
    """flexpyirt's own parent fit: MML SEs (Oakes) and FA delta-method SEs against mirt's."""
    case = load(name)
    ours = _projected(project(parent_fit(name), case.data, method=method))  # type: ignore[arg-type]
    for k, (value, se) in _reference(case, KEYS[method], se="oakes").items():
        assert ours[k][0] == pytest.approx(value, abs=TOL_PARAM), k
        if se is not None:
            assert ours[k][1] == pytest.approx(se, rel=TOL_SE_REL), k
