"""Numerical agreement with R mirt for M4 ability scoring (VALIDATION.md V13).

Reference file ``tests/reference/v13_fscores.json`` is generated by
``validation/r/m4_scoring_reference.R`` with ``optimizer = "NR"``, ``accelerate = "none"``,
``TOL = 1e-10``, and ``fscores(m, method = "EAP"/"MAP"/"ML"/"WLE", response.pattern = ...,
full.scores.SE = TRUE)`` (mirt's default ``max_theta = 20`` and ``expected.info = FALSE``).

All item and latent parameters are fixed at mirt's estimates (``free = False``) so that only
scoring is compared, and the exact marginal log-likelihood at mirt's estimates is verified first.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import pytest

from flexpyirt import (
    GPCM,
    GRM,
    FitResult,
    Model,
    Normal,
    Quadrature,
    ThreePL,
    TwoPL,
    fit,
)
from tests._reference import check_reference_meta

REFERENCE_DIR = Path(__file__).parent / "reference"
REFERENCE_FILE = "v13_fscores.json"
TOL_LOGLIK_REL = 1e-6
TOL_EAP = 1e-5
TOL_THETA = 1e-4
TOL_SE_REL = 1e-3

CASES = [
    "lsat7_2pl",
    "science_grm",
    "science_gpcm",
    "v11_3pl",
    "twogroup_2pl",
    "missing_2pl",
]
METHODS = ("MAP", "ML", "WLE")


def _to_float_array(values: list[Any]) -> np.ndarray:
    """Convert JSON list containing numbers, 'Inf', '-Inf', or None to a float64 ndarray."""
    out = np.empty(len(values), dtype=float)
    for i, v in enumerate(values):
        if v is None:
            out[i] = np.nan
        elif v == "Inf":
            out[i] = np.inf
        elif v == "-Inf":
            out[i] = -np.inf
        else:
            out[i] = float(v)
    return out


def _to_pattern_df(rows: list[list[Any]], items: list[str]) -> pd.DataFrame:
    arr = np.asarray(
        [[np.nan if v is None else float(v) for v in row] for row in rows], dtype=float
    )
    return pd.DataFrame(arr, columns=items)


@dataclass(frozen=True)
class Case:
    name: str
    raw: dict[str, Any]
    spec: Model
    quadrature: Quadrature
    train_data: pd.DataFrame
    train_group: np.ndarray | None

    @property
    def score_patterns(self) -> pd.DataFrame:
        return _to_pattern_df(self.raw["score_patterns"], self.raw["items"])

    @property
    def score_group(self) -> np.ndarray | None:
        if not self.spec.is_multigroup:
            return None
        return np.asarray(self.raw["score_groups"])

    def ref_scores(self, method: str) -> tuple[np.ndarray, np.ndarray]:
        sc = self.raw["fscores"][method]
        return _to_float_array(sc["theta"]), _to_float_array(sc["se"])


@cache
def _bundle() -> dict[str, Any]:
    raw = dict(json.loads((REFERENCE_DIR / REFERENCE_FILE).read_text()))
    check_reference_meta(raw["meta"], require_grid_check=True)
    return raw


@cache
def load(name: str) -> Case:
    raw = dict(_bundle()["cases"][name])
    check_reference_meta(raw["meta"], require_grid_check=True)
    items = list(raw["items"])
    n_cat = int(raw["meta"]["n_cat"])
    lo, hi = (float(v) for v in raw["meta"]["theta_lim"])
    quad = Quadrature.equispaced(int(raw["meta"]["quadpts"]), lim=(lo, hi))

    if name == "lsat7_2pl":
        spec = Model.uniform(TwoPL(), items=items)
    elif name == "science_grm":
        spec = Model.uniform(GRM(n_cat=n_cat), items=items)
    elif name == "science_gpcm":
        spec = Model.uniform(GPCM(n_cat=n_cat), items=items)
    elif name == "v11_3pl":
        spec = Model.uniform(ThreePL(), items=items)
    elif name == "twogroup_2pl":
        spec = (
            Model.uniform(TwoPL(), items=items)
            .with_groups(ref=Normal.standard(), focal=Normal.free())
            .equal_across_groups(items=raw["anchors"])
        )
    elif name == "missing_2pl":
        spec = Model.uniform(TwoPL(), items=items)
    else:
        raise KeyError(name)

    src_ref = raw["meta"].get("source_reference")
    if src_ref is None:
        pat_df = _to_pattern_df(raw["train_patterns"], items)
        counts = np.asarray(raw["train_counts"], dtype=int)
        train_data = pat_df.loc[pat_df.index.repeat(counts)].reset_index(drop=True)
        train_group = None
    else:
        src = dict(json.loads((REFERENCE_DIR / str(src_ref)).read_text()))
        pat_df = _to_pattern_df(src["patterns"], list(src["items"]))
        counts = np.asarray(src["counts"], dtype=int)
        train_data = pat_df.loc[pat_df.index.repeat(counts)].reset_index(drop=True)
        train_group = (
            np.repeat(np.asarray(src["pattern_groups"]), counts) if spec.is_multigroup else None
        )

    return Case(name, raw, spec, quad, train_data, train_group)


@cache
def _fixed_at_mirt(name: str) -> FitResult:
    """Fix every item and latent parameter at mirt's estimates."""
    case = load(name)
    table = case.spec.parameter_table(case.train_data, group=case.train_group)
    values = []
    for g, item, param in zip(table["group"], table["item"], table["param"], strict=True):
        est = case.raw["slope_intercept"][g]
        values.append(est["latent"][param] if item == "__latent__" else est["params"][item][param])
    table["value"] = np.asarray(values, dtype=float)
    table["free"] = False
    return fit(
        case.spec,
        case.train_data,
        group=case.train_group,
        table=table,
        quadrature=case.quadrature,
        se=None,
    )


@pytest.mark.parametrize("name", CASES)
def test_loglik_at_mirt_estimates(name: str) -> None:
    """Marginal log-likelihood at mirt's fixed estimates matches mirt's logLik."""
    case = load(name)
    res = _fixed_at_mirt(name)
    ref = float(case.raw["loglik"])
    assert abs(res.loglik - ref) <= TOL_LOGLIK_REL * abs(ref)


@pytest.mark.parametrize("name", CASES)
def test_eap_agrees_with_mirt(name: str) -> None:
    """EAP remains unchanged and agrees with mirt's fscores(..., method='EAP')."""
    case = load(name)
    ref_th, ref_se = case.ref_scores("EAP")
    got = _fixed_at_mirt(name).score(case.score_patterns, method="EAP", group=case.score_group)
    np.testing.assert_allclose(got["theta"].to_numpy(), ref_th, rtol=0, atol=TOL_EAP)
    np.testing.assert_allclose(got["se"].to_numpy(), ref_se, rtol=0, atol=TOL_EAP)


@pytest.mark.parametrize("method", METHODS)
@pytest.mark.parametrize("name", CASES)
def test_map_ml_wle_agree_with_mirt(name: str, method: str) -> None:
    """V13: MAP, ML, and WLE theta and SE agree with mirt (extreme conventions exact)."""
    case = load(name)
    ref_th, ref_se = case.ref_scores(method)
    got = _fixed_at_mirt(name).score(
        case.score_patterns,
        method=method,  # type: ignore[arg-type]
        group=case.score_group,
    )
    got_th = got["theta"].to_numpy()
    got_se = got["se"].to_numpy()

    # Exact agreement on extreme / non-finite conventions (-inf, +inf, NaN).
    np.testing.assert_array_equal(np.isnan(got_th), np.isnan(ref_th))
    np.testing.assert_array_equal(np.isposinf(got_th), np.isposinf(ref_th))
    np.testing.assert_array_equal(np.isneginf(got_th), np.isneginf(ref_th))
    np.testing.assert_array_equal(np.isfinite(got_se), np.isfinite(ref_se))

    fin = np.isfinite(ref_th)
    assert fin.any()
    np.testing.assert_allclose(got_th[fin], ref_th[fin], rtol=0, atol=TOL_THETA)
    fin_se = np.isfinite(ref_se)
    assert fin_se.any()
    np.testing.assert_allclose(got_se[fin_se], ref_se[fin_se], rtol=TOL_SE_REL, atol=0)


def test_ml_3pl_bimodal_global_supremum_returns_neg_inf() -> None:
    """Bimodal 3PL pattern where f(-inf) exceeds the interior local mode returns -inf.

    Intentional difference from mirt (DESIGN.md §15.23, VALIDATION.md V13): on pattern index
    1285 of ``v11_3pl.json`` (sum score 4/20), the log-likelihood has a strictly concave
    interior local maximum at theta ≈ -0.9079 (f ≈ -8.6132, SE ≈ 1.2855), separated by a local
    minimum from the lower-asymptote plateau where f(-20) ≈ -8.5319 > f(-0.9079). mirt's local
    ``nlm()`` search starting from EAP stops at the interior local mode and returns finite
    ``(-0.9079, 1.2855)``, whereas flexpyirt compares ``f(theta_hat)`` against ``f(±20)`` and
    returns the true global supremum ``(-inf, NaN)`` (the actual maximum likelihood).
    """
    src = json.loads((REFERENCE_DIR / "v11_3pl.json").read_text())
    items = list(src["items"])
    pat = pd.DataFrame([src["patterns"][1285]], columns=items, dtype=float)
    res = _fixed_at_mirt("v11_3pl")
    ml = res.score(pat, method="ML")
    assert ml["theta"].iloc[0] == -np.inf
    assert np.isnan(ml["se"].iloc[0])
