"""V39: M2 / M2* and S-X2 for confirmatory multidimensional models vs R mirt (VALIDATION.md).

Reference file ``tests/reference/v39_fit_multidim.json`` is generated by
``validation/r/m6_fit_multidim_reference.R`` (mirt version in its meta): ``M2()`` and
``itemfit(fit_stats = "S_X2")`` on the four V14 models (2D 2PL simple structure, 2D 2PL with a
cross-loading, 2D GRM, 3D 2PL; correlated factors) at mirt's V14 estimates, on the fit's product
grid.

- S-X2 is compared with mirt directly (degrees of freedom identical).
- mirt's ``M2()`` leaves the free factor correlations out of :math:`\\Delta_2` while subtracting
  them in ``df``. ``_latent_in_delta=False`` reproduces mirt's raw output; the default (every
  free parameter in :math:`\\Delta_2`) is compared with ``exact_with_latent``, recomputed in R
  from mirt's own pieces plus the analytic correlation columns.

Like every mirt comparison the module is in the slow tier, except the S-X2 comparison of the
smallest case and the test of the rejected model structures, which share one cheap fit and run in
the fast tier.
"""

from __future__ import annotations

import dataclasses
import json
from functools import cache
from pathlib import Path
from typing import Any

import jax.numpy as jnp
import numpy as np
import pandas as pd
import pytest

from flexpyirt import BAEM, GRM, FitResult, Model, Normal, Quadrature, TwoPL, _m2, fit
from flexpyirt._compile import LATENT_ITEM, coerce_groups, coerce_responses, compile_problem
from flexpyirt.errors import SpecificationError
from tests._reference import check_reference_meta

REFERENCE_DIR = Path(__file__).parent / "reference"
CASES = ("mirt2d_2pl_simple", "mirt2d_2pl_cross", "mirt2d_grm", "mirt3d_2pl")
M2_COLUMNS = ["m2", "df", "p", "rmsea", "rmsea_5", "rmsea_95", "srmsr", "tli", "cfi"]
FAST_CASE = "mirt2d_2pl_simple"
SX2_CASES = [
    pytest.param(name, "mincell_1", marks=() if name == FAST_CASE else pytest.mark.slow)
    for name in CASES
] + [pytest.param("mirt2d_grm", "mincell_3", marks=pytest.mark.slow)]


@cache
def _bundle() -> dict[str, Any]:
    raw = json.loads((REFERENCE_DIR / "v39_fit_multidim.json").read_text())
    check_reference_meta(raw["meta"])
    return dict(raw["cases"])


@cache
def _source(name: str) -> tuple[Model, pd.DataFrame, Quadrature, dict[str, Any]]:
    ref = _bundle()[name]
    src = json.loads((REFERENCE_DIR / f"{ref['source']}.json").read_text())["cases"][name]
    items = list(src["items"])
    item_model = GRM(int(src["meta"]["n_cat"])) if ref["itemtype"] == "graded" else TwoPL()
    spec = Model.uniform(item_model, items=items).with_factors(
        {k: list(v) for k, v in src["factors"].items()}
    )
    pats = pd.DataFrame(np.asarray(src["patterns"], dtype=float), columns=items)
    df = pats.loc[pats.index.repeat(src["counts"])].reset_index(drop=True)
    lo, hi = ref["theta_lim"]
    quad = Quadrature.equispaced(int(ref["quadpts"]), bounds=(float(lo), float(hi)))
    assert quad.n_points**spec.n_factors == int(ref["n_nodes"])
    return spec, df, quad, src["estimates"]


def _mirt_value(estimates: dict[str, Any], item: str, param: str) -> float:
    if item == LATENT_ITEM:
        return float(estimates["latent"][param])
    return float(estimates["params"][item][param])


@cache
def _at_mirt(name: str) -> FitResult:
    """A result whose free parameters are exactly mirt's V14 estimates (free flags kept)."""
    spec, df, quad, estimates = _source(name)
    table = spec.parameter_table(df)
    table["value"] = [
        _mirt_value(estimates, item, param)
        for item, param in zip(table["item"], table["param"], strict=True)
    ]
    # Started at mirt's optimum, EM stops within a few cycles; the estimates are then overwritten.
    res = fit(spec, df, table=table, method=BAEM(tol=1e-6), quadrature=quad, se=None)
    eta = np.array(res._eta, dtype=float)
    free = res.parameters[res.parameters["free"]]
    for item, param, fid in zip(free["item"], free["param"], free["free_id"], strict=True):
        eta[int(fid)] = _mirt_value(estimates, item, param)
    assert np.max(np.abs(eta - np.asarray(res._eta))) < 1e-3
    return dataclasses.replace(res, _eta=eta)


@cache
def _refit(name: str) -> FitResult:
    spec, df, quad, _ = _source(name)
    res = fit(spec, df, method=BAEM(tol=1e-9, max_iter=20000), quadrature=quad, se=None)
    assert res.converged
    return res


def _m2_no_latent(res: FitResult, name: str) -> _m2.M2Result:
    """M2 with the free correlations left out of Delta (mirt's convention)."""
    spec, df, quad, _ = _source(name)
    y = coerce_responses(df, spec)
    codes, _ = coerce_groups(None, spec, y.shape[0], require_all=False)
    compiled = compile_problem(spec, y, codes, res.parameters, quad)
    return _m2.m2_statistic(
        compiled.problem,
        jnp.asarray(res._eta),
        y,
        n_params=res.n_params,
        n_categories=[m.kernel.n_categories for _, m in spec.items],
        _latent_in_delta=False,
    )


@pytest.mark.slow
@pytest.mark.parametrize("name", CASES)
def test_parameter_counts(name: str) -> None:
    ref = _bundle()[name]
    res = _at_mirt(name)
    assert res.n_params == int(ref["nest"])
    latent = res.parameters[res.parameters["item"] == LATENT_ITEM]
    assert int(latent["free"].sum()) == int(ref["n_free_latent"])


@pytest.mark.parametrize(("name", "key"), SX2_CASES)
def test_s_x2_at_mirt_estimates(name: str, key: str) -> None:
    ref = _bundle()[name]["sx2"][key]
    _, df, _, _ = _source(name)
    out = _at_mirt(name).item_fit(df, min_cell=ref["mincell"])
    assert list(out.columns) == ["item", "s_x2", "df", "rmsea", "p"]
    assert list(out["item"]) == ref["item"]
    np.testing.assert_array_equal(out["df"].to_numpy(), np.asarray(ref["df"]))
    np.testing.assert_allclose(out["s_x2"], ref["S_X2"], rtol=1e-9)
    np.testing.assert_allclose(out["rmsea"], ref["RMSEA"], rtol=1e-8, atol=1e-12)
    np.testing.assert_allclose(out["p"], ref["p"], rtol=1e-8, atol=1e-12)


@pytest.mark.slow
@pytest.mark.parametrize("name", CASES)
def test_m2_at_mirt_estimates_matches_mirt_without_latent_columns(name: str) -> None:
    ref = _bundle()[name]["m2"]["mirt"]
    got = _m2_no_latent(_at_mirt(name), name)
    assert got.df == int(ref["df"])
    np.testing.assert_allclose(got.m2, ref["M2"], rtol=1e-8)
    np.testing.assert_allclose(got.p, ref["p"], rtol=1e-8, atol=1e-10)
    np.testing.assert_allclose(got.rmsea, ref["RMSEA"], rtol=1e-8, atol=1e-10)
    np.testing.assert_allclose(got.rmsea_lower, ref["RMSEA_5"], rtol=0.0, atol=1e-4)
    np.testing.assert_allclose(got.rmsea_upper, ref["RMSEA_95"], rtol=0.0, atol=1e-4)
    np.testing.assert_allclose(got.srmsr, ref["SRMSR"], rtol=1e-9)
    if name == "mirt2d_grm":
        assert np.isnan(got.tli) and np.isnan(got.cfi)
    else:
        np.testing.assert_allclose(got.tli, ref["TLI"], rtol=1e-7)
        np.testing.assert_allclose(got.cfi, ref["CFI"], rtol=1e-7)


@pytest.mark.slow
@pytest.mark.parametrize("name", CASES)
def test_m2_at_mirt_estimates_matches_exact_with_latent(name: str) -> None:
    """The public ``m2()`` (free correlations in Delta) against the exact R statistic."""
    bundle = _bundle()[name]["m2"]
    ref, raw = bundle["exact_with_latent"], bundle["mirt"]
    _, df, _, _ = _source(name)
    out = _at_mirt(name).m2(df)
    assert list(out.columns) == M2_COLUMNS
    row = out.iloc[0]
    assert int(row["df"]) == int(ref["df"]) == int(raw["df"])
    assert int(ref["n_delta_cols"]) == int(_bundle()[name]["nest"])
    np.testing.assert_allclose(row["m2"], ref["M2"], rtol=1e-8)
    np.testing.assert_allclose(row["p"], ref["p"], rtol=1e-8, atol=1e-10)
    np.testing.assert_allclose(row["rmsea"], ref["RMSEA"], rtol=1e-8, atol=1e-10)
    np.testing.assert_allclose(row["rmsea_5"], ref["RMSEA_5"], rtol=0.0, atol=1e-4)
    np.testing.assert_allclose(row["rmsea_95"], ref["RMSEA_95"], rtol=0.0, atol=1e-4)
    np.testing.assert_allclose(row["srmsr"], raw["SRMSR"], rtol=1e-9)
    if name == "mirt2d_grm":
        assert np.isnan(row["tli"]) and np.isnan(row["cfi"])
    else:
        np.testing.assert_allclose(row["tli"], ref["TLI"], rtol=1e-7)
        np.testing.assert_allclose(row["cfi"], ref["CFI"], rtol=1e-7)
    # The correlation columns can only shrink the orthogonal complement's quadratic form.
    assert float(row["m2"]) < float(raw["M2"])


@pytest.mark.slow
@pytest.mark.parametrize("name", CASES)
def test_refit_matches_reference(name: str) -> None:
    """Fitted from default starting values: the level at which the estimates agree (V14)."""
    bundle = _bundle()[name]
    _, df, _, _ = _source(name)
    res = _refit(name)
    assert res.loglik == pytest.approx(bundle["loglik"], rel=1e-9)

    ref = bundle["m2"]["exact_with_latent"]
    row = res.m2(df).iloc[0]
    assert int(row["df"]) == int(ref["df"])
    np.testing.assert_allclose(row["m2"], ref["M2"], rtol=1e-5)
    np.testing.assert_allclose(row["p"], ref["p"], rtol=1e-5, atol=1e-8)
    np.testing.assert_allclose(row["srmsr"], bundle["m2"]["mirt"]["SRMSR"], rtol=1e-5)
    np.testing.assert_allclose(_m2_no_latent(res, name).m2, bundle["m2"]["mirt"]["M2"], rtol=1e-5)

    for sx2 in bundle["sx2"].values():
        out = res.item_fit(df, min_cell=sx2["mincell"])
        np.testing.assert_array_equal(out["df"].to_numpy(), np.asarray(sx2["df"]))
        np.testing.assert_allclose(out["s_x2"], sx2["S_X2"], rtol=1e-5)
        np.testing.assert_allclose(out["p"], sx2["p"], rtol=1e-5, atol=1e-10)


def test_unsupported_multidimensional_structures_are_rejected() -> None:
    """The guards read the model only, so a fitted result is given each structure in turn."""
    name = FAST_CASE
    spec, df, _, _ = _source(name)
    res = _at_mirt(name)
    items = [item for item, _ in spec.items]
    base = Model.uniform(TwoPL(), items=items)
    bifactor = base.with_bifactor(specific={"s1": items[:6], "s2": items[6:]})
    two_tier = base.with_two_tier(
        primary={"p1": items[:6], "p2": items[6:]}, specific={"s": items[2:8]}
    )
    multigroup = spec.with_groups(
        ref=Normal.standard(), focal=Normal.standard()
    ).equal_across_groups(items=items)
    for reduced_spec in (bifactor, two_tier):
        reduced = dataclasses.replace(res, _model=reduced_spec)
        with pytest.raises(SpecificationError, match="bifactor or two-tier"):
            reduced.m2(df)
        with pytest.raises(SpecificationError, match="bifactor, two-tier or multiple-group"):
            reduced.item_fit(df)
    grouped = dataclasses.replace(res, _model=multigroup)
    with pytest.raises(SpecificationError, match="multiple-group multidimensional"):
        grouped.item_fit(df, group=np.tile(["ref", "focal"], len(df) // 2))
