"""Numerical agreement with R mirt for M3 3PL and 4PL (VALIDATION.md V11).

Reference files are generated by ``validation/r/m3_reference.R`` with ``optimizer = "NR"``,
``accelerate = "none"``, ``TOL = 1e-10`` on 61 equally spaced points on [-6, 6]. mirt estimates
``g`` and ``u`` on the logit scale and reports logit-scale SEs; the reference script converts
them to the natural scale via the delta method so they are directly comparable to flexpyirt's
natural-scale estimates and SEs.
"""

from __future__ import annotations

import json
import warnings
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import pytest

from flexpyirt import BAEM, FitResult, FourPL, Model, Quadrature, ThreePL, fit
from flexpyirt.errors import HeywoodWarning
from tests._reference import check_reference_meta

REFERENCE_DIR = Path(__file__).parent / "reference"
METHOD = BAEM(tol=1e-9, max_iter=20000)
TOL_LOGLIK_REL = 1e-6
TOL_PARAM = 1e-4
TOL_SE_REL = 1e-3
TOL_EAP = 1e-5
CASES = ["v11_3pl", "v11_4pl"]


@dataclass(frozen=True)
class Case:
    name: str
    raw: dict[str, Any]
    spec: Model
    quadrature: Quadrature

    @property
    def patterns(self) -> pd.DataFrame:
        return pd.DataFrame(
            np.asarray(self.raw["patterns"], dtype=float), columns=self.raw["items"]
        )

    @property
    def counts(self) -> np.ndarray:
        return np.asarray(self.raw["counts"], dtype=int)

    @property
    def data(self) -> pd.DataFrame:
        return self.patterns.loc[self.patterns.index.repeat(self.counts)].reset_index(drop=True)

    def params(self, key: str = "estimates") -> pd.DataFrame:
        rows = {
            item: {k: v for k, v in vals.items() if k != "raw_logit"}
            for item, vals in self.raw[key]["all"]["params"].items()
        }
        frame: pd.DataFrame = pd.DataFrame(rows).T
        return frame.loc[list(self.raw["items"])]


@cache
def load(name: str) -> Case:
    raw = dict(json.loads((REFERENCE_DIR / f"{name}.json").read_text()))
    check_reference_meta(raw["meta"], require_richardson=True, require_grid_check=True)
    items = raw["items"]
    item_model = ThreePL() if raw["meta"]["itemtype"] == "3PL" else FourPL()
    return Case(name, raw, Model.uniform(item_model, items=items), Quadrature.equispaced())


@cache
def _fit(name: str, se: str) -> FitResult:
    case = load(name)
    with warnings.catch_warnings():
        warnings.simplefilter("error", HeywoodWarning)
        return fit(
            case.spec,
            case.data,
            method=METHOD,
            quadrature=case.quadrature,
            se=se,  # type: ignore[arg-type]
        )


@cache
def _fixed_at_mirt(name: str) -> FitResult:
    """All parameters fixed at mirt's estimates (no EM step moves anything)."""
    case = load(name)
    table = case.spec.parameter_table(case.data)
    est = case.raw["estimates"]["all"]
    values = [
        est["latent"][param] if item == "__latent__" else est["params"][item][param]
        for item, param in zip(table["item"], table["param"], strict=True)
    ]
    table["value"] = np.asarray(values, dtype=float)
    table["free"] = False
    return fit(case.spec, case.data, table=table, quadrature=case.quadrature, se=None)


@pytest.mark.parametrize("name", CASES)
def test_loglik(name: str) -> None:
    case, res = load(name), _fit(name, "oakes")
    assert res.converged
    ref = float(case.raw["loglik"])
    assert abs(res.loglik - ref) <= TOL_LOGLIK_REL * abs(ref)
    assert res.loglik >= _fixed_at_mirt(name).loglik - 1e-8


@pytest.mark.parametrize("name", CASES)
def test_parameters(name: str) -> None:
    case, res = load(name), _fit(name, "oakes")
    ref = case.params()
    ours = res.items.set_index("item").loc[ref.index]
    for p in ("a", "d", "g", "u"):
        np.testing.assert_allclose(ours[p], ref[p].astype(float), rtol=0, atol=TOL_PARAM)


@pytest.mark.parametrize(
    ("name", "se", "key"),
    [
        *[(n, "oakes", "estimates") for n in CASES],
        *[(n, "hessian", "se_richardson") for n in CASES],
    ],
)
def test_standard_errors(name: str, se: str, key: str) -> None:
    """V10/V11: Oakes vs mirt Oakes, direct Hessian vs mirt Richardson (natural scale)."""
    case, res = load(name), _fit(name, se)
    ref = case.params(key)
    ours = res.items.set_index("item").loc[ref.index]
    for col in ("a_se", "d_se", "g_se", "u_se"):
        expected = ref[col].astype(float).to_numpy()
        got = ours[col].to_numpy()
        free = np.isfinite(expected)
        np.testing.assert_allclose(got[free], expected[free], rtol=TOL_SE_REL)
        assert np.isnan(got[~free]).all()


@pytest.mark.parametrize("name", CASES)
def test_eap_with_mirt_parameters(name: str) -> None:
    case = load(name)
    scores = _fixed_at_mirt(name).score(case.patterns)
    np.testing.assert_allclose(scores["theta"], case.raw["eap"]["theta"], rtol=0, atol=TOL_EAP)
    np.testing.assert_allclose(scores["se"], case.raw["eap"]["se"], rtol=0, atol=TOL_EAP)


@pytest.mark.parametrize("name", CASES)
def test_em_monotone(name: str) -> None:
    ll = _fit(name, "oakes").history["loglik"].to_numpy()
    assert np.all(np.diff(ll) >= -1e-9 * np.abs(ll[1:]))


@pytest.mark.parametrize("name", CASES)
def test_oakes_equals_hessian(name: str) -> None:
    oakes, hess = _fit(name, "oakes"), _fit(name, "hessian")
    assert oakes.vcov is not None and hess.vcov is not None
    np.testing.assert_allclose(oakes.vcov, hess.vcov, rtol=1e-6, atol=1e-12)
