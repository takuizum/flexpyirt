"""Numerical agreement with R mirt for M2 (VALIDATION.md V3, V4, V5, V9).

Reference files have per-group ``estimates`` (generated by validation/r/m2_reference.R).
V4 and V5 free the latent mean/variance and use 81 points on [-8, 8] on both sides
(VALIDATION.md, DESIGN.md §14.9).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import pytest

from flexpyirt import BAEM, GRM, FitResult, Model, Normal, Quadrature, TwoPL, fit

REFERENCE_DIR = Path(__file__).parent / "reference"
METHOD = BAEM(tol=1e-9, max_iter=20000)
TOL_LOGLIK_REL = 1e-6
TOL_PARAM = 1e-4
TOL_SE_REL = 1e-3
TOL_EAP = 1e-5
WIDE = Quadrature.equispaced(81, lim=(-8, 8))


@dataclass(frozen=True)
class Case:
    name: str
    raw: dict[str, Any]
    spec: Model
    quadrature: Quadrature

    @property
    def groups(self) -> list[str]:
        return list(self.raw["groups"])

    @property
    def patterns(self) -> pd.DataFrame:
        rows = [[np.nan if v is None else v for v in row] for row in self.raw["patterns"]]
        return pd.DataFrame(np.asarray(rows, dtype=float), columns=self.raw["items"])

    @property
    def counts(self) -> np.ndarray:
        return np.asarray(self.raw["counts"], dtype=int)

    @property
    def data(self) -> pd.DataFrame:
        return self.patterns.loc[self.patterns.index.repeat(self.counts)].reset_index(drop=True)

    @property
    def group(self) -> np.ndarray | None:
        if not self.spec.is_multigroup:
            return None
        return np.repeat(np.asarray(self.raw["pattern_groups"]), self.counts)

    def params(self, group: str, key: str = "estimates") -> pd.DataFrame:
        frame: pd.DataFrame = pd.DataFrame(self.raw[key][group]["params"]).T
        return frame.loc[list(self.raw["items"])]

    def latent(self, group: str, key: str = "estimates") -> dict[str, float | None]:
        return dict(self.raw[key][group]["latent"])


def _raw(name: str) -> dict[str, Any]:
    return dict(json.loads((REFERENCE_DIR / f"{name}.json").read_text()))


@cache
def load(name: str) -> Case:
    raw = _raw(name)
    items = raw["items"]
    if name == "v3_science_grm":
        return Case(name, raw, Model.uniform(GRM(n_cat=4), items=items), Quadrature.equispaced())
    if name == "v9_missing_2pl":
        return Case(name, raw, Model.uniform(TwoPL(), items=items), Quadrature.equispaced())
    if name == "v5_fipc_2pl":
        spec = (
            Model.uniform(TwoPL(), items=items)
            .fix_from(pd.DataFrame(raw["bank"]))
            .with_latent(Normal.free())
        )
        return Case(name, raw, spec, WIDE)
    if name == "v4_twogroup_2pl":
        spec = (
            Model.uniform(TwoPL(), items=items)
            .with_groups(ref=Normal.standard(), focal=Normal.free())
            .equal_across_groups(items=raw["anchors"])
        )
        return Case(name, raw, spec, WIDE)
    raise KeyError(name)


CASES = ["v3_science_grm", "v4_twogroup_2pl", "v5_fipc_2pl", "v9_missing_2pl"]


@cache
def _fit(name: str, se: str) -> FitResult:
    case = load(name)
    return fit(
        case.spec,
        case.data,
        group=case.group,
        method=METHOD,
        quadrature=case.quadrature,
        se=se,  # type: ignore[arg-type]
    )


@cache
def _fixed_at_mirt(name: str) -> FitResult:
    """All parameters fixed at mirt's estimates (no EM step moves anything)."""
    case = load(name)
    table = case.spec.parameter_table(case.data, group=case.group)
    values = []
    for g, item, param in zip(table["group"], table["item"], table["param"], strict=True):
        est = case.raw["estimates"][g]
        values.append(est["latent"][param] if item == "__latent__" else est["params"][item][param])
    table["value"] = np.asarray(values, dtype=float)
    table["free"] = False
    return fit(
        case.spec, case.data, group=case.group, table=table, quadrature=case.quadrature, se=None
    )


def _items(res: FitResult, group: str) -> pd.DataFrame:
    items = res.items
    if "group" in items:
        items = items[items["group"] == group]
    return items.set_index("item")


@pytest.mark.parametrize("name", CASES)
def test_loglik(name: str) -> None:
    case, res = load(name), _fit(name, "oakes")
    assert res.converged
    ref = float(case.raw["loglik"])
    assert abs(res.loglik - ref) <= TOL_LOGLIK_REL * abs(ref)
    assert res.loglik >= _fixed_at_mirt(name).loglik - 1e-8


@pytest.mark.parametrize("name", CASES)
def test_parameters(name: str) -> None:
    case, res = load(name), _fit(name, "oakes")
    for g in case.groups:
        ref = case.params(g)
        ours = _items(res, g).loc[ref.index]
        for p in [c for c in ref.columns if not c.endswith("_se")]:
            np.testing.assert_allclose(ours[p], ref[p].astype(float), rtol=0, atol=TOL_PARAM)
        lat = res.latent.set_index("group").loc[g]
        ref_lat = case.latent(g)
        assert lat["mean"] == pytest.approx(ref_lat["mean"], abs=TOL_PARAM)
        assert lat["var"] == pytest.approx(ref_lat["var"], abs=TOL_PARAM)


@pytest.mark.parametrize(
    ("name", "se", "key"),
    [
        *[(n, "oakes", "estimates") for n in CASES],
        *[(n, "hessian", "se_richardson") for n in CASES],
    ],
)
def test_standard_errors(name: str, se: str, key: str) -> None:
    """V10: Oakes vs mirt Oakes, direct Hessian vs mirt Richardson."""
    case, res = load(name), _fit(name, se)
    for g in case.groups:
        ref = case.params(g, key)
        ours = _items(res, g).loc[ref.index]
        for col in [c for c in ref.columns if c.endswith("_se")]:
            expected = ref[col].astype(float).to_numpy()
            got = ours[col].to_numpy()
            free = np.isfinite(expected)
            np.testing.assert_allclose(got[free], expected[free], rtol=TOL_SE_REL)
            assert np.isnan(got[~free]).all()
        lat = res.latent.set_index("group").loc[g]
        for p in ("mean", "var"):
            ref_se = case.latent(g, key)[f"{p}_se"]
            if ref_se is None:
                assert np.isnan(lat[f"{p}_se"])
            else:
                assert lat[f"{p}_se"] == pytest.approx(ref_se, rel=TOL_SE_REL)


@pytest.mark.parametrize("name", [n for n in CASES if "eap" in _raw(n)])
def test_eap_with_mirt_parameters(name: str) -> None:
    case = load(name)
    scores = _fixed_at_mirt(name).score(case.patterns)
    np.testing.assert_allclose(scores["theta"], case.raw["eap"]["theta"], rtol=0, atol=TOL_EAP)
    np.testing.assert_allclose(scores["se"], case.raw["eap"]["se"], rtol=0, atol=TOL_EAP)


@pytest.mark.parametrize("name", CASES)
def test_em_monotone(name: str) -> None:
    ll = _fit(name, "oakes").history["loglik"].to_numpy()
    assert np.all(np.diff(ll) >= -1e-9 * np.abs(ll[1:]))


@pytest.mark.parametrize("name", CASES)
def test_oakes_equals_hessian(name: str) -> None:
    oakes, hess = _fit(name, "oakes"), _fit(name, "hessian")
    assert oakes.vcov is not None and hess.vcov is not None
    np.testing.assert_allclose(oakes.vcov, hess.vcov, rtol=1e-6, atol=1e-12)


def test_anchor_items_are_equal_across_groups() -> None:
    case, res = load("v4_twogroup_2pl"), _fit("v4_twogroup_2pl", "oakes")
    items = res.items.set_index(["group", "item"])
    for item in case.raw["anchors"]:
        assert items.loc[("ref", item), "a"] == items.loc[("focal", item), "a"]
        assert items.loc[("ref", item), "d"] == items.loc[("focal", item), "d"]
    d = items["d"].to_dict()
    assert d[("ref", "q10")] != d[("focal", "q10")]


def test_fipc_keeps_bank_values() -> None:
    case, res = load("v5_fipc_2pl"), _fit("v5_fipc_2pl", "oakes")
    bank = pd.DataFrame(case.raw["bank"]).set_index("item")
    items = res.items.set_index("item").loc[bank.index]
    np.testing.assert_array_equal(items["a"], bank["a"])
    np.testing.assert_array_equal(items["d"], bank["d"])
    assert items["a_se"].isna().all()


def test_multigroup_scoring_uses_group_latent() -> None:
    case, res = load("v4_twogroup_2pl"), _fit("v4_twogroup_2pl", "oakes")
    row = case.patterns.iloc[[0, 0]]
    scores = res.score(row, group=["ref", "focal"])
    assert scores["theta"].iloc[1] > scores["theta"].iloc[0]  # focal mean is higher
