"""Numerical agreement with R mirt for bifactor models (VALIDATION.md V32, DESIGN.md §17.1).

Reference file ``tests/reference/v32_bifactor.json`` is generated by
``validation/r/m7_bifactor_reference.R`` with mirt's ``bfactor()`` (Gibbons–Hedeker dimension
reduction), ``optimizer = "NR"``, ``accelerate = "none"``, ``TOL = 1e-10``, ``SE.type = "Oakes"``
and 31 points per dimension on ``[-6, 6]`` (mirt's ``bfactor()`` default). EAPs come from mirt's
``fscores()`` on the full product grid with 15 points per dimension, which equals the factorized
posterior on the same one-dimensional grid.
"""

from __future__ import annotations

import json
import warnings
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import pytest

from flexpyirt import BAEM, GRM, FitResult, Model, Quadrature, TwoPL, fit
from flexpyirt.errors import HeywoodWarning
from tests._reference import check_reference_meta

# mirt reference comparison: nightly and release-PR CI only (CONTRIBUTING.md, "Tests").
pytestmark = pytest.mark.slow

REFERENCE_FILE = Path(__file__).parent / "reference" / "v32_bifactor.json"
SQUAREM = (False, True)
TOL_LOGLIK_REL = 1e-6
TOL_PARAM = 1e-4
TOL_SE_REL = 1e-3
TOL_EAP = 1e-5

CASES = ["bifactor_2pl", "bifactor_grm"]


@dataclass(frozen=True)
class Case:
    name: str
    raw: dict[str, Any]
    spec: Model
    quadrature: Quadrature

    @property
    def patterns(self) -> pd.DataFrame:
        return pd.DataFrame(
            np.asarray(self.raw["patterns"], dtype=float), columns=self.raw["items"]
        )

    @property
    def data(self) -> pd.DataFrame:
        counts = np.asarray(self.raw["counts"], dtype=int)
        return self.patterns.loc[self.patterns.index.repeat(counts)].reset_index(drop=True)

    @property
    def item_params(self) -> pd.DataFrame:
        frame: pd.DataFrame = pd.DataFrame(self.raw["estimates"]["params"]).T.astype(float)
        return frame.loc[list(self.raw["items"])]


@cache
def _bundle() -> dict[str, Any]:
    raw: dict[str, Any] = dict(json.loads(REFERENCE_FILE.read_text()))
    check_reference_meta(raw["meta"], require_grid_check=True)
    return raw


@cache
def load(name: str) -> Case:
    raw = dict(_bundle()["cases"][name])
    meta = raw["meta"]
    check_reference_meta(meta, require_grid_check=True)
    item_model = GRM(int(meta["n_cat"])) if meta["itemtype"] == "graded" else TwoPL()
    specific = {k: list(v) for k, v in raw["specific"].items()}
    spec = Model.uniform(item_model, items=raw["items"]).with_bifactor(
        specific=specific, general=str(raw["general"])
    )
    assert spec.n_factors == int(meta["n_factors"])
    lo, hi = meta["theta_lim"]
    quad = Quadrature.equispaced(int(meta["quadpts"]), bounds=(float(lo), float(hi)))
    assert quad.n_points**2 == int(meta["n_nodes"])
    return Case(name=name, raw=raw, spec=spec, quadrature=quad)


@cache
def _fit(name: str, se: str, squarem: bool = False) -> FitResult:
    case = load(name)
    with warnings.catch_warnings():
        warnings.simplefilter("error", HeywoodWarning)
        return fit(
            case.spec,
            case.data,
            method=BAEM(tol=1e-9, max_iter=20000, squarem=squarem),
            quadrature=case.quadrature,
            se=se,  # type: ignore[arg-type]
        )


@cache
def _fixed_at_mirt(name: str, n_points: int | None = None) -> FitResult:
    """All parameters fixed at mirt's estimates, optionally on another grid."""
    case = load(name)
    table = case.spec.parameter_table(case.data)
    est_items = case.raw["estimates"]["params"]
    est_lat = case.raw["estimates"]["latent"]
    table["value"] = [
        float(est_lat[param]) if item == "__latent__" else float(est_items[item][param])
        for item, param in zip(table["item"], table["param"], strict=True)
    ]
    table["free"] = False
    quad = case.quadrature
    if n_points is not None:
        quad = Quadrature.equispaced(n_points, bounds=(quad.lower, quad.upper))
    return fit(case.spec, case.data, table=table, quadrature=quad, se=None)


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_loglik(name: str, squarem: bool) -> None:
    case, res = load(name), _fit(name, "oakes", squarem)
    assert res.converged
    ref = float(case.raw["loglik"])
    assert abs(res.loglik - ref) <= TOL_LOGLIK_REL * abs(ref)
    assert res.loglik >= _fixed_at_mirt(name).loglik - 1e-8


@pytest.mark.parametrize("name", CASES)
def test_loglik_at_mirt_parameters(name: str) -> None:
    """The reduced marginal likelihood at mirt's estimates equals mirt's log-likelihood."""
    case = load(name)
    ref = float(case.raw["loglik"])
    assert _fixed_at_mirt(name).loglik == pytest.approx(ref, rel=1e-9)


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_item_parameters(name: str, squarem: bool) -> None:
    case, res = load(name), _fit(name, "oakes", squarem)
    ref = case.item_params
    ours = res.items.set_index("item").loc[ref.index]
    for p in [c for c in ref.columns if not c.endswith("_se")]:
        np.testing.assert_allclose(ours[p].to_numpy(), ref[p].to_numpy(), rtol=0, atol=TOL_PARAM)


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_standard_errors_oakes(name: str, squarem: bool) -> None:
    """V32: Oakes SEs vs mirt Oakes for general and specific slopes and intercepts."""
    case, res = load(name), _fit(name, "oakes", squarem)
    ref = case.item_params
    ours = res.items.set_index("item").loc[ref.index]
    for col in [c for c in ref.columns if c.endswith("_se")]:
        expected = ref[col].to_numpy()
        got = ours[col].to_numpy()
        free = np.isfinite(expected)
        np.testing.assert_allclose(got[free], expected[free], rtol=TOL_SE_REL)
        assert np.isnan(got[~free]).all()


@pytest.mark.parametrize("name", CASES)
def test_latent_fixed(name: str) -> None:
    case, res = load(name), _fit(name, "oakes")
    lat = res.latent.iloc[0]
    for p, v in case.raw["estimates"]["latent"].items():
        assert float(lat[p]) == pytest.approx(float(v), abs=0)
        assert np.isnan(float(lat[f"{p}_se"]))


@pytest.mark.parametrize("name", CASES)
def test_eap_with_mirt_parameters(name: str) -> None:
    case = load(name)
    eap = case.raw["eap"]
    idx = np.asarray(eap["pattern_indices"], dtype=int)
    pats = case.patterns.iloc[idx].reset_index(drop=True)
    scores = _fixed_at_mirt(name, int(eap["quadpts"])).score(pats, method="EAP")
    for f in case.spec.factor_names:
        np.testing.assert_allclose(scores[f"theta_{f}"], eap["theta"][f], rtol=0, atol=TOL_EAP)
        np.testing.assert_allclose(scores[f"se_{f}"], eap["se"][f], rtol=0, atol=TOL_EAP)


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_em_monotone(name: str, squarem: bool) -> None:
    res = _fit(name, "oakes", squarem)
    ll = res.history["loglik"].to_numpy()
    assert np.all(np.diff(ll) >= -1e-9 * np.abs(ll[1:]))
    assert res.loglik >= ll[-1] - 1e-9 * abs(ll[-1])


@pytest.mark.parametrize("name", CASES)
def test_oakes_equals_hessian(name: str) -> None:
    oakes, hess = _fit(name, "oakes", True), _fit(name, "hessian", True)
    assert oakes.vcov is not None and hess.vcov is not None
    np.testing.assert_allclose(oakes.vcov, hess.vcov, rtol=1e-6, atol=1e-12)
