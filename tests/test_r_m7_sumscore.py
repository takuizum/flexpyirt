"""Agreement of the summed-score distribution kernel with R (VALIDATION.md V36, DESIGN.md §18.1).

Reference file ``tests/reference/v36_sumscore.json`` is generated by
``validation/r/m7_sumscore_reference.R``: the Poisson-binomial distribution from ``poibin``
(Hong, 2013; recursive formula, DFT-CF, normal and refined normal approximations),
``stats::dpois`` for the Poisson approximation, and for polytomous items mirt's summed-score
table (``fscores(method = "EAPsum", full.scores = FALSE)``) together with the item category
probabilities on the grid, so that only the kernel is under test.
"""

from __future__ import annotations

import json
from functools import cache
from pathlib import Path
from typing import Any

import numpy as np
import pytest

from flexpyirt import summed_score_distribution

REFERENCE_FILE = Path(__file__).parent / "reference" / "v36_sumscore.json"
DICHOTOMOUS = ["uniform_10", "twopl_50", "extreme_200", "rare_300", "equal_40"]
POLYTOMOUS = ["grm_10", "mixed_10"]
TOL_ABS = 1e-13
TOL_REL = 1e-11


@cache
def _bundle() -> dict[str, Any]:
    raw: dict[str, Any] = dict(json.loads(REFERENCE_FILE.read_text()))
    return raw


def _probs(name: str) -> np.ndarray:
    p = np.asarray(_bundle()["dichotomous"][name]["p"], dtype=float)
    return np.stack([1.0 - p, p], axis=-1)


def _reference(name: str, key: str) -> np.ndarray:
    return np.asarray(_bundle()["dichotomous"][name][key], dtype=float)


@pytest.mark.parametrize("name", DICHOTOMOUS)
@pytest.mark.parametrize("method", ["recursion", "fft"])
def test_exact_methods_match_poibin(name: str, method: str) -> None:
    """Both exact methods against poibin's recursive formula (cdf) and DFT-CF (cdf and pmf)."""
    pmf = np.asarray(summed_score_distribution(_probs(name), method=method))  # type: ignore[arg-type]
    np.testing.assert_allclose(np.cumsum(pmf), _reference(name, "cdf_rf"), rtol=0, atol=TOL_ABS)
    np.testing.assert_allclose(np.cumsum(pmf), _reference(name, "cdf_dftcf"), rtol=0, atol=TOL_ABS)
    np.testing.assert_allclose(pmf, _reference(name, "pmf_dftcf"), rtol=0, atol=TOL_ABS)


@pytest.mark.parametrize("name", DICHOTOMOUS)
def test_log_recursion_matches_poibin(name: str) -> None:
    log_pmf = np.asarray(summed_score_distribution(_probs(name), log=True))
    np.testing.assert_allclose(np.exp(log_pmf), _reference(name, "pmf_dftcf"), rtol=0, atol=TOL_ABS)


@pytest.mark.parametrize("name", DICHOTOMOUS)
@pytest.mark.parametrize(("method", "key"), [("normal", "cdf_na"), ("refined_normal", "cdf_rna")])
def test_normal_approximations_match_poibin(name: str, method: str, key: str) -> None:
    pmf = np.asarray(summed_score_distribution(_probs(name), method=method))  # type: ignore[arg-type]
    np.testing.assert_allclose(np.cumsum(pmf), _reference(name, key), rtol=0, atol=TOL_ABS)


@pytest.mark.parametrize("name", DICHOTOMOUS)
def test_poisson_approximation_matches_dpois(name: str) -> None:
    pmf = np.asarray(summed_score_distribution(_probs(name), method="poisson"))
    np.testing.assert_allclose(pmf, _reference(name, "pmf_poisson"), rtol=TOL_REL, atol=1e-300)


def _polytomous(name: str) -> tuple[dict[str, Any], np.ndarray, int]:
    case = dict(_bundle()["polytomous"][name])
    traces = [np.asarray(t, dtype=float) for t in case["traces"]]
    probs = np.zeros((traces[0].shape[0], len(traces), max(t.shape[1] for t in traces)))
    for j, tr in enumerate(traces):
        probs[:, j, : tr.shape[1]] = tr
    return case, probs, sum(t.shape[1] - 1 for t in traces)


@pytest.mark.parametrize("name", POLYTOMOUS)
@pytest.mark.parametrize("method", ["recursion", "fft"])
def test_marginal_distribution_matches_mirt_eapsum(name: str, method: str) -> None:
    """``N sum_q w_q L(s | theta_q)`` equals the ``expected`` column of mirt's EAPsum table."""
    case, probs, total = _polytomous(name)
    lik = np.asarray(summed_score_distribution(probs, method=method))  # type: ignore[arg-type]
    weights = np.asarray(case["weights"], dtype=float)
    expected = np.asarray(case["expected"], dtype=float)
    assert list(case["sum_scores"]) == list(range(total + 1))
    np.testing.assert_allclose(lik[:, total + 1 :], 0.0, atol=1e-14)
    n_persons = float(case["n"])
    got = n_persons * (weights @ lik[:, : total + 1])
    if method == "fft":
        # The FFT's error is absolute (about 1e-16 per probability), not relative.
        np.testing.assert_allclose(got, expected, rtol=0, atol=n_persons * TOL_ABS)
    else:
        np.testing.assert_allclose(got, expected, rtol=TOL_REL, atol=0)


@pytest.mark.parametrize("name", POLYTOMOUS)
def test_summed_score_eap_matches_mirt(name: str) -> None:
    """The posterior of theta given the summed score, built from the kernel, gives mirt's EAP."""
    case, probs, total = _polytomous(name)
    lik = np.asarray(summed_score_distribution(probs))[:, : total + 1]
    weights = np.asarray(case["weights"], dtype=float)
    nodes = np.asarray(case["nodes"], dtype=float)
    posterior = lik * weights[:, None]
    posterior = posterior / posterior.sum(axis=0)
    mean = nodes @ posterior
    sd = np.sqrt(nodes**2 @ posterior - mean**2)
    np.testing.assert_allclose(mean, case["eap"], rtol=0, atol=1e-12)
    np.testing.assert_allclose(sd, case["eap_sd"], rtol=0, atol=1e-12)
