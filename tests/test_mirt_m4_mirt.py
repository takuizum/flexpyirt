"""Numerical agreement with R mirt for M4 confirmatory 2-3D MIRT (VALIDATION.md V14).

Reference file ``tests/reference/v14_mirt2d.json`` is generated by
``validation/r/m4_mirt_reference.R`` with ``optimizer = "NR"``, ``accelerate = "none"``,
``TOL = 1e-10``, ``SE.type = "Oakes"``, and mirt's default product grids (31 per dimension for
2D -> 961 nodes, 15 per dimension for 3D -> 3375 nodes, both on ``[-6, 6]``).
"""

from __future__ import annotations

import json
import warnings
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import pytest

from flexpyirt import BAEM, GRM, FitResult, Model, Quadrature, TwoPL, fit
from flexpyirt.errors import HeywoodWarning
from flexpyirt.latent import latent_param_names
from tests._reference import check_reference_meta

REFERENCE_DIR = Path(__file__).parent / "reference"
REFERENCE_FILE = "v14_mirt2d.json"
SQUAREM = (False, True)
TOL_LOGLIK_REL = 1e-6
TOL_PARAM = 1e-4
TOL_LATENT = 1e-4
TOL_SE_REL = 1e-3
TOL_EAP = 1e-5

CASES = [
    "mirt2d_2pl_simple",
    "mirt2d_2pl_cross",
    "mirt2d_grm",
    "mirt3d_2pl",
]


@dataclass(frozen=True)
class Case:
    name: str
    raw: dict[str, Any]
    spec: Model
    quadrature: Quadrature

    @property
    def patterns(self) -> pd.DataFrame:
        return pd.DataFrame(
            np.asarray(self.raw["patterns"], dtype=float), columns=self.raw["items"]
        )

    @property
    def counts(self) -> np.ndarray:
        return np.asarray(self.raw["counts"], dtype=int)

    @property
    def data(self) -> pd.DataFrame:
        return self.patterns.loc[self.patterns.index.repeat(self.counts)].reset_index(drop=True)

    @property
    def item_params(self) -> pd.DataFrame:
        frame: pd.DataFrame = pd.DataFrame(self.raw["estimates"]["params"]).T.astype(float)
        return frame.loc[list(self.raw["items"])]

    @property
    def latent_params(self) -> dict[str, float]:
        return {
            k: (np.nan if v is None else float(v))
            for k, v in self.raw["estimates"]["latent"].items()
        }


@cache
def _bundle() -> dict[str, Any]:
    raw: dict[str, Any] = dict(json.loads((REFERENCE_DIR / REFERENCE_FILE).read_text()))
    check_reference_meta(raw["meta"], require_grid_check=True)
    return raw


@cache
def load(name: str) -> Case:
    raw = dict(_bundle()["cases"][name])
    meta = raw["meta"]
    check_reference_meta(meta, require_grid_check=True)
    items = list(raw["items"])
    factors = {k: list(v) for k, v in raw["factors"].items()}
    item_model = GRM(int(meta["n_cat"])) if meta["itemtype"] == "graded" else TwoPL()
    spec = Model.uniform(item_model, items=items).with_factors(factors)
    lo, hi = meta["theta_lim"]
    quad = Quadrature.equispaced(int(meta["quadpts"]), lim=(float(lo), float(hi)))
    assert quad.n_points**spec.n_factors == int(meta["n_nodes"])
    return Case(name=name, raw=raw, spec=spec, quadrature=quad)


@cache
def _fit(name: str, se: str, squarem: bool = False) -> FitResult:
    case = load(name)
    with warnings.catch_warnings():
        warnings.simplefilter("error", HeywoodWarning)
        return fit(
            case.spec,
            case.data,
            method=BAEM(tol=1e-9, max_iter=20000, squarem=squarem),
            quadrature=case.quadrature,
            se=se,  # type: ignore[arg-type]
        )


@cache
def _fixed_at_mirt(name: str) -> FitResult:
    """All parameters fixed at mirt's estimates (no EM step moves anything)."""
    case = load(name)
    table = case.spec.parameter_table(case.data)
    est_items = case.raw["estimates"]["params"]
    est_lat = case.latent_params
    values = [
        est_lat[param] if item == "__latent__" else float(est_items[item][param])
        for item, param in zip(table["item"], table["param"], strict=True)
    ]
    table["value"] = np.asarray(values, dtype=float)
    table["free"] = False
    return fit(case.spec, case.data, table=table, quadrature=case.quadrature, se=None)


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_loglik(name: str, squarem: bool) -> None:
    case, res = load(name), _fit(name, "oakes", squarem)
    assert res.converged
    ref = float(case.raw["loglik"])
    assert abs(res.loglik - ref) <= TOL_LOGLIK_REL * abs(ref)
    assert res.loglik >= _fixed_at_mirt(name).loglik - 1e-8


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_item_parameters(name: str, squarem: bool) -> None:
    case, res = load(name), _fit(name, "oakes", squarem)
    ref = case.item_params
    ours = res.items.set_index("item").loc[ref.index]
    param_cols = [c for c in ref.columns if not c.endswith("_se")]
    for p in param_cols:
        np.testing.assert_allclose(ours[p].to_numpy(), ref[p].to_numpy(), rtol=0, atol=TOL_PARAM)


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_latent_correlations(name: str, squarem: bool) -> None:
    case, res = load(name), _fit(name, "oakes", squarem)
    ref = case.latent_params
    lat = res.latent.iloc[0]
    for p in latent_param_names(case.spec.n_factors):
        assert float(lat[p]) == pytest.approx(ref[p], abs=TOL_LATENT)


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_standard_errors_oakes(name: str, squarem: bool) -> None:
    """V14: Oakes SEs vs mirt Oakes for item slopes, intercepts, and latent correlations."""
    case, res = load(name), _fit(name, "oakes", squarem)
    ref = case.item_params
    ours = res.items.set_index("item").loc[ref.index]
    se_cols = [c for c in ref.columns if c.endswith("_se")]
    for col in se_cols:
        expected = ref[col].to_numpy()
        got = ours[col].to_numpy()
        free = np.isfinite(expected)
        np.testing.assert_allclose(got[free], expected[free], rtol=TOL_SE_REL)
        assert np.isnan(got[~free]).all()

    ref_lat = case.latent_params
    lat = res.latent.iloc[0]
    for p in latent_param_names(case.spec.n_factors):
        se_col = f"{p}_se"
        expected_se = ref_lat[se_col]
        got_se = float(lat[se_col])
        if np.isfinite(expected_se):
            assert got_se == pytest.approx(expected_se, rel=TOL_SE_REL)
        else:
            assert np.isnan(got_se)


@pytest.mark.parametrize("name", CASES)
def test_eap_with_mirt_parameters(name: str) -> None:
    case = load(name)
    idx = np.asarray(case.raw["eap"]["pattern_indices"], dtype=int)
    pats = case.patterns.iloc[idx].reset_index(drop=True)
    scores = _fixed_at_mirt(name).score(pats, method="EAP")
    for f in case.spec.factor_names:
        np.testing.assert_allclose(
            scores[f"theta_{f}"], case.raw["eap"]["theta"][f], rtol=0, atol=TOL_EAP
        )
        np.testing.assert_allclose(
            scores[f"se_{f}"], case.raw["eap"]["se"][f], rtol=0, atol=TOL_EAP
        )


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_em_monotone(name: str, squarem: bool) -> None:
    res = _fit(name, "oakes", squarem)
    ll = res.history["loglik"].to_numpy()
    assert np.all(np.diff(ll) >= -1e-9 * np.abs(ll[1:]))
    assert res.loglik >= ll[-1] - 1e-9 * abs(ll[-1])


@pytest.mark.parametrize("name", CASES)
def test_oakes_equals_hessian(name: str) -> None:
    oakes, hess = _fit(name, "oakes", True), _fit(name, "hessian", True)
    assert oakes.vcov is not None and hess.vcov is not None
    np.testing.assert_allclose(oakes.vcov, hess.vcov, rtol=1e-6, atol=1e-12)
