@cache
def _reference() -> dict[str, Any]:
    raw = dict(json.loads((REFERENCE_DIR / "v26_local_dependence.json").read_text()))
    check_reference_meta(raw["meta"])
    return raw


def _case(name: str) -> dict[str, Any]:
    return next(c for c in _reference()["cases"] if c["name"] == name)


def _data(case: dict[str, Any]) -> pd.DataFrame:
    rows = [[np.nan if v is None else v for v in row] for row in case["data"]]
    return pd.DataFrame(rows, columns=case["items"], dtype=float)


@cache
def _fit(name: str) -> FitResult:
    case = _case(name)
    df = _data(case)
    kernel = TwoPL() if case["itemtype"] == "2PL" else GRM(int(np.nanmax(df.to_numpy())) + 1)
    return fit(
        Model.uniform(kernel, items=case["items"]),
        df,
        method=BAEM(tol=1e-9, max_iter=20000),
        se=None,
    )


CASES = ["lsat7_2pl", "science_grm", "sim_2pl_ld_missing"]


@pytest.mark.parametrize("name", CASES)
def test_local_dependence_matches_mirt(name: str) -> None:
    case = _case(name)
    res = _fit(name)
    assert res.loglik == pytest.approx(case["loglik"], rel=1e-9)
    ld = res.local_dependence(_data(case))
    ref = pd.DataFrame(case["pairs"]).sort_values(["i", "j"]).reset_index(drop=True)
    names = case["items"]
    assert list(ld.pairs["item_i"]) == [names[i] for i in ref["i"]]
    assert list(ld.pairs["item_j"]) == [names[j] for j in ref["j"]]
    # atol: a pair with X2 near 1e-5 moves by about 2e-10 with the stopping point of the
    # 1e-9-tolerance EM, which is more than 1e-5 relative (VALIDATION.md, tolerances).
    np.testing.assert_allclose(ld.pairs["x2"], ref["x2"], rtol=1e-5, atol=1e-8)
    np.testing.assert_allclose(ld.pairs["g2"], ref["g2"], rtol=1e-5, atol=1e-8)
    np.testing.assert_allclose(ld.pairs["cramer_v"], ref["cramer_v"], rtol=0, atol=1e-6)
    np.testing.assert_allclose(ld.pairs["q3"], ref["q3"], rtol=0, atol=1e-6)
    np.testing.assert_allclose(ld.q3.to_numpy()[np.triu_indices(len(names), 1)], ld.pairs["q3"])
    assert ld.q3_mean == pytest.approx(float(np.mean(ref["q3"])), abs=1e-6)
    np.testing.assert_allclose(ld.pairs["q3_star"], ld.pairs["q3"] - ld.q3_mean)
    assert ld.max_q3_star == pytest.approx(float(ld.pairs["q3_star"].max()))


def test_local_dependence_flags_the_dependent_pair() -> None:
    ld = _fit("sim_2pl_ld_missing").local_dependence(_data(_case("sim_2pl_ld_missing")))
    top = ld.pairs.sort_values("x2", ascending=False).iloc[0]
    assert (top["item_i"], top["item_j"]) == ("s1", "s2")
    assert top["q3_star"] == pytest.approx(ld.max_q3_star)
    assert top["cramer_v"] > 0
    assert top["p_x2"] < 1e-3
    assert (ld.pairs["n"] < len(_data(_case("sim_2pl_ld_missing")))).all()


@pytest.mark.parametrize(
    ("table", "expected"),
    [
        (np.array([[10.0, 0.0], [0.0, 10.0]]), 1.0),
        (np.array([[0.0, 10.0], [10.0, 0.0]]), -1.0),
        # C = 2 * (1 + 2) + 1 * 2 = 8, D = 0.
        (np.array([[2.0, 1.0, 0.0], [0.0, 1.0, 2.0]]), 1.0),
        # C = 1 * 1 = 1, D = 2 * 1 = 2.
        (np.array([[1.0, 2.0], [1.0, 1.0]]), -1.0 / 3.0),
        (np.zeros((2, 2)), np.nan),
    ],
)
def test_goodman_kruskal_gamma(table: np.ndarray, expected: float) -> None:
    got = goodman_kruskal_gamma(table)
    if np.isnan(expected):
        assert np.isnan(got)
    else:
        assert got == pytest.approx(expected)


def test_goodman_kruskal_gamma_brute_force() -> None:
    rng = np.random.default_rng(0)
    table = rng.integers(0, 6, size=(4, 3)).astype(float)
    conc = disc = 0.0
    for a in range(4):
        for b in range(3):
            for a2 in range(a + 1, 4):
                for b2 in range(3):
                    if b2 > b:
                        conc += table[a, b] * table[a2, b2]
                    elif b2 < b:
                        disc += table[a, b] * table[a2, b2]
    assert goodman_kruskal_gamma(table) == pytest.approx((conc - disc) / (conc + disc))


def test_model_parallel_analysis_matches_ltm_unidim_test() -> None:
    ref = _reference()["unidim_test"]
    case = _case(ref["case"])
    res = model_parallel_analysis(
        _fit(ref["case"]), _data(case), key=jax.random.key(1), n_replications=500
    )
    np.testing.assert_allclose(res.observed, ref["observed"], rtol=0, atol=2e-4)
    assert res.statistic == res.observed[1]
    second = res.replications[:, 1]
    se = np.sqrt(second.var() / second.size + ref["boot_second_sd"] ** 2 / ref["B"])
    assert abs(second.mean() - ref["boot_second_mean"]) / se <= 4.5
    assert np.quantile(second, 0.95) == pytest.approx(ref["boot_second_q"][2], abs=0.02)
    expected_p = (1 + np.sum(second >= res.statistic)) / (second.size + 1)
    assert res.p_value == pytest.approx(expected_p)
    assert res.eigen_type == "max"


