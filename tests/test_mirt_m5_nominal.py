"""Numerical agreement with R mirt for M5 nominal response model (VALIDATION.md V23).

Reference files are generated by ``validation/r/m5_nominal_reference.R`` with ``optimizer = "NR"``,
``accelerate = "none"``, ``TOL = 1e-10``, 61 points on [-6, 6]:
- ``v23_nominal_science``: ``mirt::Science`` recoded ``0..3``, ``itemtype = "nominal"``
- ``v23_nominal_sim``: simulated nominal ($J = 10, K = 4, N = 3000$), including swapped interior
  categories (``q09``) and a negative scoring coefficient ``ak1 < 0`` (``q10``)
- ``v23_nominal_mixed``: mixed model ($J = 10, N = 2500$: 5 nominal items $K = 4$ + 5 2PL items)
- ``v23_nominal_unordered``: simulated nominal ($J = 8, K = 4, N = 3000$) with six non-monotone
  items (including ``ak > K - 1``); mirt's NR from the GPCM point stops at a local maximum there,
  so the reference restarts NR from the best alternative start (``meta.reference_start``), while
  flexpyirt fits from its own default starting values
- MAP, ML, and WLE scoring (``fscores``) on a subset of patterns per case, with an independent R
  log-likelihood scan (``ml_scan``) for every pattern mirt scores as ``±Inf`` by ML
- S-X2 item fit (``itemfit``) at the reference estimates, and the log-likelihoods of alternative
  mirt starts (``alt_starts``: GPCM-point NR, default-start NR and BFGS, three random NR starts)
- ``v23_nominal_2d``: two-factor confirmatory nominal ($J = 8, K = 4, N = 3000$, 31 points per
  dimension on [-6, 6]) with Oakes SEs and EAP (V14-style).
"""

from __future__ import annotations

import json
import warnings
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any, Literal

import numpy as np
import pandas as pd
import pytest

from flexpyirt import BAEM, FitResult, Model, Nominal, Quadrature, TwoPL, fit
from flexpyirt.errors import HeywoodWarning
from flexpyirt.items import ItemModel
from tests._reference import check_reference_meta

REFERENCE_DIR = Path(__file__).parent / "reference"
SQUAREM = (False, True)
TOL_LOGLIK_REL = 1e-6
TOL_PARAM = 1e-4
TOL_SE_REL = 1e-3
TOL_EAP = 1e-5
TOL_SCORE_THETA = 1e-4
TOL_SCORE_SE_REL = 1e-3
TOL_SX2_REL = 1e-6
CASES = ["v23_nominal_science", "v23_nominal_sim", "v23_nominal_mixed", "v23_nominal_unordered"]
CASE_2D = "v23_nominal_2d"


@dataclass(frozen=True)
class Case:
    name: str
    raw: dict[str, Any]
    spec: Model
    quadrature: Quadrature

    @property
    def patterns(self) -> pd.DataFrame:
        return pd.DataFrame(
            np.asarray(self.raw["patterns"], dtype=float), columns=self.raw["items"]
        )

    @property
    def counts(self) -> np.ndarray:
        return np.asarray(self.raw["counts"], dtype=int)

    @property
    def data(self) -> pd.DataFrame:
        return self.patterns.loc[self.patterns.index.repeat(self.counts)].reset_index(drop=True)

    def params(self, key: str = "estimates") -> pd.DataFrame:
        frame: pd.DataFrame = pd.DataFrame(self.raw[key]["all"]["params"]).T
        return frame.loc[list(self.raw["items"])]

    def latent(self, key: str = "estimates") -> dict[str, float | None]:
        return dict(self.raw[key]["all"]["latent"])


def _build_spec(items: list[str], itemtype: str | list[str], n_cat: int | list[int]) -> Model:
    if isinstance(itemtype, str):
        assert isinstance(n_cat, int)
        return Model.uniform(Nominal(n_cat=n_cat), items=items)
    assert isinstance(n_cat, list)
    item_models: dict[str, ItemModel] = {}
    for name, it, k in zip(items, itemtype, n_cat, strict=True):
        if it == "nominal":
            item_models[name] = Nominal(n_cat=int(k))
        elif it == "2PL":
            item_models[name] = TwoPL()
        else:
            raise ValueError(f"Unexpected itemtype {it!r}")
    return Model.from_items(item_models)


@cache
def load(name: str) -> Case:
    raw = dict(json.loads((REFERENCE_DIR / f"{name}.json").read_text()))
    meta = raw["meta"]
    check_reference_meta(meta, require_richardson=True, require_grid_check=True)
    items = list(raw["items"])
    spec = _build_spec(items, meta["itemtype"], meta["n_cat"])
    lim = (float(meta["theta_lim"][0]), float(meta["theta_lim"][1]))
    quad = Quadrature.equispaced(int(meta["quadpts"]), lim=lim)
    return Case(name, raw, spec, quad)


@cache
def _fit(name: str, se: str, squarem: bool = False) -> FitResult:
    case = load(name)
    with warnings.catch_warnings():
        warnings.simplefilter("error", HeywoodWarning)
        return fit(
            case.spec,
            case.data,
            method=BAEM(tol=1e-9, max_iter=20000, squarem=squarem),
            quadrature=case.quadrature,
            se=se,  # type: ignore[arg-type]
        )


@cache
def _fixed_at_mirt(name: str) -> FitResult:
    """All parameters fixed at mirt's estimates (no EM step moves anything)."""
    case = load(name)
    table = case.spec.parameter_table(case.data)
    est = case.raw["estimates"]["all"]
    values = [
        est["latent"][param] if item == "__latent__" else est["params"][item][param]
        for item, param in zip(table["item"], table["param"], strict=True)
    ]
    table["value"] = np.asarray(values, dtype=float)
    table["free"] = False
    return fit(case.spec, case.data, table=table, quadrature=case.quadrature, se=None)


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_loglik(name: str, squarem: bool) -> None:
    case, res = load(name), _fit(name, "oakes", squarem)
    assert res.converged
    ref = float(case.raw["loglik"])
    assert abs(res.loglik - ref) <= TOL_LOGLIK_REL * abs(ref)
    assert res.loglik >= _fixed_at_mirt(name).loglik - 1e-8


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_parameters(name: str, squarem: bool) -> None:
    case, res = load(name), _fit(name, "oakes", squarem)
    ref = case.params()
    ours = res.items.set_index("item").loc[ref.index]
    for p in [c for c in ref.columns if not c.endswith("_se")]:
        expected = ref[p].astype(float).to_numpy()
        got = ours[p].to_numpy(dtype=float)
        mask = np.isfinite(expected)
        np.testing.assert_allclose(got[mask], expected[mask], rtol=0, atol=TOL_PARAM)
        assert np.isnan(got[~mask]).all()
    lat = res.latent.iloc[0]
    ref_lat = case.latent()
    assert float(lat["mean"]) == pytest.approx(ref_lat["mean"], abs=TOL_PARAM)
    assert float(lat["var"]) == pytest.approx(ref_lat["var"], abs=TOL_PARAM)


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize(
    ("name", "se", "key"),
    [
        *[(n, "oakes", "estimates") for n in CASES],
        *[(n, "hessian", "se_richardson") for n in CASES],
    ],
)
def test_standard_errors(name: str, se: str, key: str, squarem: bool) -> None:
    """V23/V10: Oakes vs mirt Oakes, direct Hessian vs mirt Richardson."""
    case, res = load(name), _fit(name, se, squarem)
    ref = case.params(key)
    ours = res.items.set_index("item").loc[ref.index]
    for col in [c for c in ref.columns if c.endswith("_se")]:
        expected = ref[col].astype(float).to_numpy()
        got = ours[col].to_numpy(dtype=float)
        free = np.isfinite(expected)
        np.testing.assert_allclose(got[free], expected[free], rtol=TOL_SE_REL)
        assert np.isnan(got[~free]).all()
    lat = res.latent.iloc[0]
    ref_lat = case.latent(key)
    for p in ("mean", "var"):
        ref_se = ref_lat[f"{p}_se"]
        if ref_se is None:
            assert np.isnan(float(lat[f"{p}_se"]))
        else:
            assert float(lat[f"{p}_se"]) == pytest.approx(ref_se, rel=TOL_SE_REL)


@pytest.mark.parametrize("name", CASES)
def test_eap_with_mirt_parameters(name: str) -> None:
    case = load(name)
    scores = _fixed_at_mirt(name).score(case.patterns)
    np.testing.assert_allclose(scores["theta"], case.raw["eap"]["theta"], rtol=0, atol=TOL_EAP)
    np.testing.assert_allclose(scores["se"], case.raw["eap"]["se"], rtol=0, atol=TOL_EAP)


def _decode(values: list[Any]) -> np.ndarray:
    """Decode mirt scores written as numbers, ``"Inf"`` / ``"-Inf"``, or ``null`` (NA)."""
    table = {"Inf": np.inf, "-Inf": -np.inf, None: np.nan}
    return np.array([table[v] if v in table else float(v) for v in values], dtype=float)


def _category_slopes(case: Case) -> list[np.ndarray]:
    """Per item, the category slopes ``a * ak_c`` at mirt's estimates (2PL: ``a * (0, 1)``)."""
    params = case.raw["estimates"]["all"]["params"]
    out = []
    for item in case.raw["items"]:
        p = params[item]
        if "ak1" in p:
            n_ak = sum(1 for k in p if k.startswith("ak") and not k.endswith("_se"))
            top = float(n_ak + 1)
            ak = [0.0, *(float(p[f"ak{k}"]) for k in range(1, n_ak + 1)), top]
        else:
            ak = [0.0, 1.0]
        out.append(float(p["a"]) * np.asarray(ak))
    return out


def _expected_ml_extremes(case: Case, pats: pd.DataFrame) -> np.ndarray:
    """``-1`` / ``+1`` where every response has the lowest / highest category slope, else ``0``.

    Uses the full scoring vectors (``ak0 = 0``, interior ``ak``, ``ak{K-1} = K - 1``), so an
    interior ``ak < 0`` or ``ak > K - 1`` moves the extreme category away from ``0`` / ``K - 1``.
    """
    y = pats.to_numpy(dtype=int)
    low = np.ones(len(y), dtype=bool)
    high = np.ones(len(y), dtype=bool)
    for j, slopes in enumerate(_category_slopes(case)):
        s_obs = slopes[y[:, j]]
        low &= s_obs == slopes.min()
        high &= s_obs == slopes.max()
    return np.where(low, -1, np.where(high, 1, 0))


def _inf_sign(x: np.ndarray) -> np.ndarray:
    return np.where(np.isposinf(x), 1, np.where(np.isneginf(x), -1, 0))


@pytest.mark.parametrize("method", ["MAP", "ML", "WLE"])
@pytest.mark.parametrize("name", CASES)
def test_fscores_with_mirt_parameters(name: str, method: Literal["MAP", "ML", "WLE"]) -> None:
    """V23d: MAP, ML, and WLE scoring on nominal patterns with parameters fixed at mirt's.

    mirt 1.46.1 ``fscores(method = "ML")`` returns ``-Inf`` / ``+Inf`` for every all-category-0 /
    all-top-category pattern regardless of the scoring coefficients (and can leave a true
    ``+Inf`` pattern at its ``max_theta = 20`` bound with SE NA). Extreme patterns are instead
    classified from the category slopes; where that says the ML estimate is interior, flexpyirt
    is compared with the independent R log-likelihood scan in ``fscores.ml_scan`` (DESIGN.md
    §16.8).
    """
    case = load(name)
    fsc = case.raw["fscores"]
    pats = pd.DataFrame(np.asarray(fsc["patterns"], dtype=float), columns=case.raw["items"])
    ref_theta = _decode(fsc[method.lower()]["theta"])
    ref_se = _decode(fsc[method.lower()]["se"])

    got = _fixed_at_mirt(name).score(pats, method=method)
    got_theta = got["theta"].to_numpy(dtype=float)
    got_se = got["se"].to_numpy(dtype=float)

    if method == "ML":
        expected = _expected_ml_extremes(case, pats)
        np.testing.assert_array_equal(_inf_sign(got_theta), expected)
        scan = fsc["ml_scan"]
        idx = np.asarray(scan["index"], dtype=int)
        scan_theta, scan_se = _decode(scan["theta"]), _decode(scan["se"])
        # The scan covers exactly the patterns mirt scores as +/-Inf or leaves at its
        # max_theta = 20 bound (nlm stopped there, SE NA) ...
        stuck = np.isinf(ref_theta) | (np.abs(ref_theta) > 19.9)
        np.testing.assert_array_equal(np.sort(idx), np.flatnonzero(stuck))
        # ... and agrees with the slope-based classification.
        np.testing.assert_array_equal(_inf_sign(scan_theta), expected[idx])
        interior = np.isfinite(scan_theta)
        if name != "v23_nominal_science":
            assert interior.any()  # each simulated case exercises mirt's raw-category rule
        for i, t, se in zip(idx[interior], scan_theta[interior], scan_se[interior], strict=True):
            assert got_theta[i] == pytest.approx(t, abs=TOL_SCORE_THETA)
            assert got_se[i] == pytest.approx(se, rel=TOL_SCORE_SE_REL)
        # Where mirt and the scan differ, the scan (true ML) is the reference.
        ref_theta[idx], ref_se[idx] = scan_theta, scan_se

    assert np.array_equal(np.isposinf(got_theta), np.isposinf(ref_theta))
    assert np.array_equal(np.isneginf(got_theta), np.isneginf(ref_theta))
    assert np.array_equal(np.isnan(got_theta), np.isnan(ref_theta))
    assert np.array_equal(np.isnan(got_se), np.isnan(ref_se))
    finite_t = np.isfinite(ref_theta)
    np.testing.assert_allclose(
        got_theta[finite_t], ref_theta[finite_t], rtol=0, atol=TOL_SCORE_THETA
    )
    finite_s = np.isfinite(ref_se)
    np.testing.assert_allclose(got_se[finite_s], ref_se[finite_s], rtol=TOL_SCORE_SE_REL, atol=0)


@pytest.mark.parametrize("name", CASES)
def test_reference_is_best_known_and_default_starts_reach_it(name: str) -> None:
    """No alternative mirt start beats the reference; flexpyirt's default starts reach it."""
    case = load(name)
    ref = float(case.raw["loglik"])
    alts = case.raw["alt_starts"]
    labels = {a["label"] for a in alts}
    assert {"gpcm_point_nr", "default_nr", "default_bfgs"} <= labels
    for alt in alts:
        if alt["loglik"] is not None:
            assert float(alt["loglik"]) <= ref + TOL_LOGLIK_REL * abs(ref)
    res = _fit(name, "oakes", False)
    assert res.loglik >= ref - TOL_LOGLIK_REL * abs(ref)
    if name == "v23_nominal_unordered":
        # mirt's NR from the GPCM point stops at a local maximum; flexpyirt does not.
        gpcm = next(a for a in alts if a["label"] == "gpcm_point_nr")
        assert float(gpcm["loglik"]) < ref - 1.0
        assert case.raw["meta"]["reference_start"] != "gpcm_point"


@pytest.mark.parametrize("name", CASES)
def test_s_x2_matches_mirt(name: str) -> None:
    """V23/V15: S-X2 item fit vs mirt ``itemfit(fit_stats = "S_X2")`` at the reference fit."""
    case = load(name)
    ref = case.raw["s_x2"]
    got = _fit(name, "oakes", False).item_fit(case.data)
    assert list(got["item"]) == list(ref["item"])
    np.testing.assert_array_equal(got["df"].to_numpy(), np.asarray(ref["df"]))
    np.testing.assert_allclose(got["s_x2"], ref["S_X2"], rtol=TOL_SX2_REL)
    # RMSEA = sqrt(max(0, X2/df - 1)/(N - 1)) magnifies the relative error of X2 by
    # X2 / (2 (X2 - df)) (13x for X2 = 6.25, df = 6), and this test evaluates S-X2 at flexpyirt's
    # own estimates (not mirt's), so propagate the S-X2 tolerance through the formula instead of
    # reusing it unchanged: |dRMSEA| <= X2 * tol / (2 df (N - 1) RMSEA).
    x2 = np.asarray(ref["S_X2"], dtype=float)
    dfs = np.asarray(ref["df"], dtype=float)
    rmsea_ref = np.asarray(ref["RMSEA"], dtype=float)
    n_obs = case.data.shape[0]
    with np.errstate(divide="ignore", invalid="ignore"):
        tol_rmsea = np.where(
            rmsea_ref > 0, x2 * TOL_SX2_REL / (2.0 * dfs * (n_obs - 1) * rmsea_ref), 1e-12
        )
    np.testing.assert_array_less(np.abs(got["rmsea"].to_numpy() - rmsea_ref), tol_rmsea + 1e-12)
    np.testing.assert_allclose(got["p"], ref["p"], rtol=1e-4, atol=1e-12)


