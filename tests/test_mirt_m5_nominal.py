# ---- V23f: two-factor confirmatory nominal model ----------------------------------------------


@cache
def _load_2d() -> tuple[dict[str, Any], Model, Quadrature, pd.DataFrame]:
    raw: dict[str, Any] = dict(json.loads((REFERENCE_DIR / f"{CASE_2D}.json").read_text()))
    meta = raw["meta"]
    check_reference_meta(meta, require_grid_check=True)
    items = list(raw["items"])
    factors = {k: list(v) for k, v in raw["factors"].items()}
    spec = Model.uniform(Nominal(int(meta["n_cat"])), items=items).with_factors(factors)
    lo, hi = meta["theta_lim"]
    quad = Quadrature.equispaced(int(meta["quadpts"]), lim=(float(lo), float(hi)))
    assert quad.n_points**spec.n_factors == int(meta["n_nodes"])
    pats = pd.DataFrame(np.asarray(raw["patterns"], dtype=float), columns=items)
    data = pats.loc[pats.index.repeat(np.asarray(raw["counts"], dtype=int))]
    return raw, spec, quad, data.reset_index(drop=True)


@cache
def _fit_2d(squarem: bool) -> FitResult:
    _, spec, quad, data = _load_2d()
    with warnings.catch_warnings():
        warnings.simplefilter("error", HeywoodWarning)
        return fit(
            spec,
            data,
            method=BAEM(tol=1e-9, max_iter=20000, squarem=squarem),
            quadrature=quad,
            se="oakes",
        )


@pytest.mark.parametrize("squarem", SQUAREM)
def test_2d_nominal_matches_mirt(squarem: bool) -> None:
    """V23f: loglik, item parameters, latent correlation, and Oakes SEs vs mirt (2D nominal)."""
    raw, _, _, _ = _load_2d()
    res = _fit_2d(squarem)
    assert res.converged
    ref_ll = float(raw["loglik"])
    assert abs(res.loglik - ref_ll) <= TOL_LOGLIK_REL * abs(ref_ll)
    assert float(raw["alt_starts"][0]["loglik"]) <= ref_ll + TOL_LOGLIK_REL * abs(ref_ll)

    ref = pd.DataFrame(raw["estimates"]["params"]).T
    ours = res.items.set_index("item").loc[ref.index]
    for col in ref.columns:
        expected = ref[col].astype(float).to_numpy()
        got = ours[col].to_numpy(dtype=float)
        if col.endswith("_se"):
            free = np.isfinite(expected)
            np.testing.assert_allclose(got[free], expected[free], rtol=TOL_SE_REL)
            assert np.isnan(got[~free]).all()
        else:
            np.testing.assert_allclose(got, expected, rtol=0, atol=TOL_PARAM)

    lat = res.latent.iloc[0]
    ref_lat = raw["estimates"]["latent"]
    assert float(lat["cor_12"]) == pytest.approx(ref_lat["cor_12"], abs=TOL_PARAM)
    assert float(lat["cor_12_se"]) == pytest.approx(ref_lat["cor_12_se"], rel=TOL_SE_REL)
    for p in ("mean_1", "mean_2", "var_1", "var_2"):
        assert float(lat[p]) == pytest.approx(float(ref_lat[p]), abs=0.0)
        assert np.isnan(float(lat[f"{p}_se"]))

    ll = res.history["loglik"].to_numpy()
    assert np.all(np.diff(ll) >= -1e-9 * np.abs(ll[1:]))


def test_2d_nominal_oakes_equals_hessian() -> None:
    _, spec, quad, data = _load_2d()
    hess = fit(spec, data, method=BAEM(tol=1e-9, squarem=True), quadrature=quad, se="hessian")
    oakes = _fit_2d(True)
    assert oakes.vcov is not None and hess.vcov is not None
    np.testing.assert_allclose(oakes.vcov, hess.vcov, rtol=1e-6, atol=1e-12)


def test_2d_nominal_eap_with_mirt_parameters() -> None:
    raw, spec, quad, data = _load_2d()
    table = spec.parameter_table(data)
    est_items = raw["estimates"]["params"]
    est_lat = raw["estimates"]["latent"]
    table["value"] = np.asarray(
        [
            float(est_lat[p]) if i == "__latent__" else float(est_items[i][p])
            for i, p in zip(table["item"], table["param"], strict=True)
        ],
        dtype=float,
    )
    table["free"] = False
    res = fit(spec, data, table=table, quadrature=quad, se=None)
    idx = np.asarray(raw["eap"]["pattern_indices"], dtype=int)
    pats = pd.DataFrame(np.asarray(raw["patterns"], dtype=float), columns=raw["items"]).iloc[idx]
    scores = res.score(pats.reset_index(drop=True), method="EAP")
    for f in spec.factor_names:
        np.testing.assert_allclose(scores[f"theta_{f}"], raw["eap"]["theta"][f], atol=TOL_EAP)
        np.testing.assert_allclose(scores[f"se_{f}"], raw["eap"]["se"][f], atol=TOL_EAP)
