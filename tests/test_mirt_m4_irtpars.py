"""Numerical agreement with R mirt for M4 delta-method IRT SEs (VALIDATION.md V12).

Reference file ``tests/reference/v12_irtpars.json`` is generated by
``validation/r/m4_irtpars_reference.R`` with ``optimizer = "NR"``, ``accelerate = "none"``,
``TOL = 1e-10``, and ``coef(m, IRTpars = TRUE, printSE = TRUE)`` (``SE.type = "Oakes"``).

Note on GPCM ``b1_se`` (VALIDATION.md V12):
    In mirt 1.46.1, ``mirt:::mirt2traditional`` has an off-by-one index bug for ``gpcm`` that
    computes ``b1_se`` by differentiating ``b2 = -(d2 - d1)/a`` with respect to ``(a, d1)`` only.
    Point estimates ``b1..b3`` and SEs ``b2_se, b3_se`` from ``coef(..., IRTpars = TRUE)`` are
    exact and compared directly; ``b1_se`` is compared against the exact delta-method SE computed
    from ``vcov(m)`` in R (``exact_delta_se``). For PCM (``a = 1`` fixed) the bug cancels and all
    of ``b1_se..b3_se`` are compared directly against mirt's ``IRTpars = TRUE`` output.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import pytest

from flexpyirt import (
    BAEM,
    GPCM,
    GRM,
    PCM,
    FitResult,
    Model,
    Normal,
    Quadrature,
    Rasch,
    TwoPL,
    fit,
)
from tests._reference import check_reference_meta

REFERENCE_DIR = Path(__file__).parent / "reference"
REFERENCE_FILE = "v12_irtpars.json"
SQUAREM = (False, True)
TOL_LOGLIK_REL = 1e-6
TOL_PARAM = 1e-4
TOL_SE_REL = 1e-3

CASES = [
    "lsat7_2pl",
    "lsat7_rasch",
    "science_grm",
    "science_gpcm",
    "science_pcm",
    "mg_2pl",
]


@dataclass(frozen=True)
class Case:
    name: str
    raw: dict[str, Any]
    spec: Model
    quadrature: Quadrature

    @property
    def groups(self) -> list[str]:
        return list(self.raw["groups"])

    @property
    def patterns(self) -> pd.DataFrame:
        return pd.DataFrame(
            np.asarray(self.raw["patterns"], dtype=float), columns=self.raw["items"]
        )

    @property
    def counts(self) -> np.ndarray:
        return np.asarray(self.raw["counts"], dtype=int)

    @property
    def data(self) -> pd.DataFrame:
        return self.patterns.loc[self.patterns.index.repeat(self.counts)].reset_index(drop=True)

    @property
    def group(self) -> np.ndarray | None:
        if not self.spec.is_multigroup:
            return None
        return np.repeat(np.asarray(self.raw["pattern_groups"]), self.counts)

    def irtpars(self, group: str) -> pd.DataFrame:
        frame: pd.DataFrame = pd.DataFrame(self.raw["irtpars"][group]).T
        return frame.loc[list(self.raw["items"])]

    def exact_delta_se(self, group: str) -> pd.DataFrame:
        frame: pd.DataFrame = pd.DataFrame(self.raw["exact_delta_se"][group]).T
        return frame.loc[list(self.raw["items"])]


@cache
def _bundle() -> dict[str, Any]:
    raw = dict(json.loads((REFERENCE_DIR / REFERENCE_FILE).read_text()))
    check_reference_meta(raw["meta"], require_grid_check=True)
    return raw


@cache
def load(name: str) -> Case:
    raw = dict(_bundle()["cases"][name])
    check_reference_meta(raw["meta"], require_grid_check=True)
    items = raw["items"]
    n_cat = int(raw["meta"]["n_cat"])
    lo, hi = (float(v) for v in raw["meta"]["theta_lim"])
    quad = Quadrature.equispaced(int(raw["meta"]["quadpts"]), lim=(lo, hi))
    if name == "lsat7_2pl":
        spec = Model.uniform(TwoPL(), items=items)
    elif name == "lsat7_rasch":
        spec = Model.uniform(Rasch(), items=items)
    elif name == "science_grm":
        spec = Model.uniform(GRM(n_cat=n_cat), items=items)
    elif name == "science_gpcm":
        spec = Model.uniform(GPCM(n_cat=n_cat), items=items)
    elif name == "science_pcm":
        spec = Model.uniform(PCM(n_cat=n_cat), items=items)
    elif name == "mg_2pl":
        spec = (
            Model.uniform(TwoPL(), items=items)
            .with_groups(ref=Normal.standard(), focal=Normal.free())
            .equal_across_groups(items=raw["anchors"])
        )
    else:
        raise KeyError(name)
    return Case(name, raw, spec, quad)


@cache
def _fit(name: str, se: str = "oakes", squarem: bool = False) -> FitResult:
    case = load(name)
    return fit(
        case.spec,
        case.data,
        group=case.group,
        method=BAEM(tol=1e-9, max_iter=20000, squarem=squarem),
        quadrature=case.quadrature,
        se=se,  # type: ignore[arg-type]
    )


@cache
def _fixed_at_mirt(name: str) -> FitResult:
    """All parameters fixed at mirt's slope-intercept estimates."""
    case = load(name)
    table = case.spec.parameter_table(case.data, group=case.group)
    values = []
    for g, item, param in zip(table["group"], table["item"], table["param"], strict=True):
        est = case.raw["slope_intercept"][g]
        values.append(est["latent"][param] if item == "__latent__" else est["params"][item][param])
    table["value"] = np.asarray(values, dtype=float)
    table["free"] = False
    return fit(
        case.spec, case.data, group=case.group, table=table, quadrature=case.quadrature, se=None
    )


def _items(res: FitResult, group: str) -> pd.DataFrame:
    items = res.items
    if "group" in items:
        items = items[items["group"] == group]
    return items.set_index("item")


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_loglik(name: str, squarem: bool) -> None:
    case, res = load(name), _fit(name, "oakes", squarem)
    assert res.converged
    ref = float(case.raw["loglik"])
    assert abs(res.loglik - ref) <= TOL_LOGLIK_REL * abs(ref)
    assert res.loglik >= _fixed_at_mirt(name).loglik - 1e-8


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_irt_thresholds(name: str, squarem: bool) -> None:
    """V12: display IRT thresholds b / bk agree with mirt's coef(..., IRTpars = TRUE)."""
    case, res = load(name), _fit(name, "oakes", squarem)
    for g in case.groups:
        ref = case.irtpars(g)
        ours = _items(res, g).loc[ref.index]
        b_cols = [c for c in ref.columns if c.startswith("b") and not c.endswith("_se")]
        assert b_cols
        for col in b_cols:
            np.testing.assert_allclose(ours[col], ref[col].astype(float), rtol=0, atol=TOL_PARAM)


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_irt_threshold_standard_errors(name: str, squarem: bool) -> None:
    """V12: delta-method SEs b_se / bk_se agree with mirt's coef(..., IRTpars=TRUE, printSE=TRUE).

    For ``science_gpcm``, ``b2_se`` and ``b3_se`` are compared directly against mirt's ``IRTpars``
    output and ``b1_se`` is compared against the exact delta-method SE computed from ``vcov(m)``
    in R (avoiding mirt 1.46.1's off-by-one bug in ``mirt:::mirt2traditional``).
    """
    case, res = load(name), _fit(name, "oakes", squarem)
    for g in case.groups:
        ref = case.irtpars(g)
        ours = _items(res, g).loc[ref.index]
        # Check a_se (finite where free, NaN where fixed).
        a_se_ref = ref["a_se"].astype(float).to_numpy()
        a_se_got = ours["a_se"].to_numpy()
        free_a = np.isfinite(a_se_ref)
        if free_a.any():
            np.testing.assert_allclose(a_se_got[free_a], a_se_ref[free_a], rtol=TOL_SE_REL)
        assert np.isnan(a_se_got[~free_a]).all()

        b_se_cols = [c for c in ref.columns if c.startswith("b") and c.endswith("_se")]
        assert b_se_cols
        if name == "science_gpcm":
            exact = case.exact_delta_se(g)
            # b2_se, b3_se directly against mirt IRTpars = TRUE.
            for col in ("b2_se", "b3_se"):
                np.testing.assert_allclose(
                    ours[col].to_numpy(), ref[col].astype(float).to_numpy(), rtol=TOL_SE_REL
                )
            # b1_se against exact delta method from mirt's vcov(m).
            np.testing.assert_allclose(
                ours["b1_se"].to_numpy(), exact["b1_se"].astype(float).to_numpy(), rtol=TOL_SE_REL
            )
            # Confirm mirt's raw b1_se actually exhibits the documented bug (>10% discrepancy).
            rel_bug = np.abs(ours["b1_se"].to_numpy() - ref["b1_se"].astype(float).to_numpy()) / (
                ours["b1_se"].to_numpy()
            )
            assert float(rel_bug.max()) > 0.1
        else:
            for col in b_se_cols:
                expected = ref[col].astype(float).to_numpy()
                got = ours[col].to_numpy()
                free = np.isfinite(expected)
                np.testing.assert_allclose(got[free], expected[free], rtol=TOL_SE_REL)
                assert np.isnan(got[~free]).all()


@pytest.mark.parametrize("name", ["lsat7_2pl", "science_grm", "science_gpcm"])
def test_oakes_equals_hessian_irt_se(name: str) -> None:
    oakes, hess = _fit(name, "oakes", False), _fit(name, "hessian", False)
    b_se_cols = [c for c in oakes.items.columns if c.startswith("b") and c.endswith("_se")]
    for col in b_se_cols:
        np.testing.assert_allclose(oakes.items[col], hess.items[col], rtol=1e-6, atol=1e-12)
