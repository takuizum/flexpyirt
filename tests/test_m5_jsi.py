"""Jackknife slope index (DESIGN.md §16.17, VALIDATION.md V31).

``tests/reference/v31_jsi.json`` is generated by ``validation/r/m5_jsi_reference.R``: mirt
``residuals(type = "JSI", fold = FALSE)`` with TOL = 1e-10 on four cases. flexpyirt refits the
same models and compares the refit; the two approximations are compared with the refit.
"""

from __future__ import annotations

import json
import warnings
from functools import cache
from typing import Any

import jax
import jax.numpy as jnp
import numpy as np
import pandas as pd
import pytest

from flexpyirt import (
    BAEM,
    GPCM,
    GRM,
    EmpiricalHistogram,
    FitResult,
    Model,
    Normal,
    Rasch,
    TwoPL,
    fit,
)
from flexpyirt._jsi import gradient_without, gradients_without
from flexpyirt.errors import FlexpyirtWarning, PrecisionError, SpecificationError
from tests._reference import REFERENCE_DIR, check_reference_meta

TIGHT = BAEM(tol=1e-10, max_iter=20000)


@cache
def _reference() -> dict[str, Any]:
    raw = dict(json.loads((REFERENCE_DIR / "v31_jsi.json").read_text()))
    check_reference_meta(raw["meta"])
    return raw


def _case(name: str) -> dict[str, Any]:
    return next(c for c in _reference()["cases"] if c["name"] == name)


def _data(case: dict[str, Any]) -> pd.DataFrame:
    rows = [[np.nan if v is None else v for v in row] for row in case["data"]]
    return pd.DataFrame(rows, columns=case["items"], dtype=float)


@cache
def _fit(name: str) -> FitResult:
    case = _case(name)
    df = _data(case)
    k = int(np.nanmax(df.to_numpy())) + 1
    kernel: Any = {"2PL": TwoPL(), "graded": GRM(k), "gpcm": GPCM(k)}[case["itemtype"]]
    return fit(Model.uniform(kernel, items=case["items"]), df, method=TIGHT)


@pytest.mark.parametrize("name", ["lsat7_2pl", "science_grm", "sim_2pl_ld_missing", "sim_gpcm_ld"])
def test_refit_matches_mirt(name: str) -> None:
    case = _case(name)
    expected = np.array([[np.nan if v is None else v for v in row] for row in case["jsi"]])
    res = _fit(name).jsi(_data(case))
    assert res.converged.all()
    np.testing.assert_allclose(res.matrix.to_numpy(), expected, atol=1e-5, equal_nan=True)


def _simulate(seed: int, n: int, n_items: int) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    theta = rng.normal(size=n)
    a = rng.uniform(0.8, 1.8, n_items)
    eta = a * theta[:, None] + rng.normal(0.0, 0.8, n_items)
    eta[:, :2] += 1.2 * rng.normal(size=n)[:, None]
    y = (rng.uniform(size=(n, n_items)) < 1 / (1 + np.exp(-eta))).astype(float)
    return pd.DataFrame(y, columns=[f"i{k}" for k in range(n_items)])


@cache
def _sim_fit() -> tuple[FitResult, pd.DataFrame]:
    df = _simulate(0, 1000, 15)
    return fit(Model.uniform(TwoPL(), items=list(df.columns)), df, method=TIGHT), df


@pytest.mark.parametrize(
    ("method", "steps", "atol"), [("newton", 1, 0.03), ("newton", 2, 0.02), ("one_step", 1, 0.05)]
)
def test_approximations_agree_with_the_refit(method: str, steps: int, atol: float) -> None:
    res, df = _sim_fit()
    refit = res.jsi(df).matrix.to_numpy()
    approx = res.jsi(df, method=method, newton_steps=steps)  # type: ignore[arg-type]
    np.testing.assert_allclose(approx.matrix.to_numpy(), refit, atol=atol, equal_nan=True)
    assert approx.method == method


def test_refit_equals_fitting_without_the_item() -> None:
    res, df = _sim_fit()
    jsi = res.jsi(df).matrix
    sub = df.drop(columns="i3")
    refit = fit(Model.uniform(TwoPL(), items=list(sub.columns)), sub, method=TIGHT)
    params = refit.parameters.set_index(["item", "param"])
    a_full = res.parameters.set_index(["item", "param"])["estimate"]
    for item in sub.columns:
        z = (a_full[(item, "a")] - params.loc[(item, "a"), "estimate"]) / params.loc[
            (item, "a"), "se"
        ]
        assert jsi.loc["i3", item] == pytest.approx(z, abs=1e-5)


def test_locally_dependent_pair_stands_out() -> None:
    res, df = _sim_fit()
    jsi = res.jsi(df)
    pairs = jsi.pairs.set_index(["item_i", "item_j"])
    assert pairs["folded"].idxmax() == ("i0", "i1")
    assert np.all(np.isnan(np.diag(jsi.matrix.to_numpy())))
    np.testing.assert_allclose(pairs["folded"], pairs["jsi_ij"] + pairs["jsi_ji"])
    assert jsi.matrix.loc["i1", "i0"] == pytest.approx(pairs.loc[("i0", "i1"), "jsi_ij"])


def test_vmapped_gradients_match_single_gradients() -> None:
    res, df = _sim_fit()
    prob = res._compiled_for(df.to_numpy().astype(np.int64))
    eta = jnp.asarray(res._eta)
    many = np.asarray(gradients_without(prob, eta, jnp.arange(3)))
    for j in range(3):
        np.testing.assert_allclose(many[j], np.asarray(gradient_without(prob, eta, jnp.asarray(j))))


def test_rasch_has_no_slopes_and_shared_slopes_work() -> None:
    df = _simulate(1, 600, 6)
    names = list(df.columns)
    rasch = fit(Model.uniform(Rasch(), items=names), df)
    assert np.isnan(rasch.jsi(df).matrix.to_numpy()).all()
    # Issue #145: with every item parameter fixed (no free parameter at all) jsi() raised
    # IndexError.
    free = fit(Model.uniform(TwoPL(), items=names), df, se=None)
    banked = fit(Model.uniform(TwoPL(), items=names).fix_from(free.items), df, se=None)
    assert banked.n_params == 0
    assert np.isnan(banked.jsi(df).matrix.to_numpy()).all()
    shared = fit(
        Model.uniform(TwoPL(), items=names).equal_across_items(items=names[2:], params=["a"]), df
    ).jsi(df)
    values = shared.matrix.loc["i0", names[2:]].to_numpy()
    assert np.isfinite(values).all() and np.allclose(values, values[0])


def test_few_items_warn_for_approximations() -> None:
    df = _simulate(2, 500, 6)
    res = fit(Model.uniform(TwoPL(), items=list(df.columns)), df)
    with pytest.warns(FlexpyirtWarning, match="method='refit'"):
        res.jsi(df, method="one_step")


@pytest.mark.parametrize(
    ("kwargs", "match"),
    [
        ({"method": "jackknife"}, "Unknown method"),
        ({"method": "newton", "newton_steps": 0}, "newton_steps"),
        ({"tol": 0.0}, "tol"),
        ({"max_iter": 0}, "max_iter"),
    ],
)
def test_invalid_options(kwargs: dict[str, Any], match: str) -> None:
    res, df = _sim_fit()
    with pytest.raises(SpecificationError, match=match):
        res.jsi(df, **kwargs)


def test_unsupported_models() -> None:
    df = _simulate(3, 400, 6)
    names = list(df.columns)
    no_se = fit(Model.uniform(TwoPL(), items=names), df, se=None)
    with pytest.raises(SpecificationError, match="standard errors"):
        no_se.jsi(df, method="one_step")
    two = fit(Model.uniform(TwoPL(), items=names[:2]), df[names[:2]])
    with pytest.raises(SpecificationError, match="three items"):
        two.jsi(df[names[:2]])
    groups = np.repeat(["g1", "g2"], 200)
    spec = Model.uniform(TwoPL(), items=names).with_groups(
        g1=Normal.standard(), g2=Normal.standard()
    )
    mg = fit(spec, df, group=groups, se=None)
    with pytest.raises(SpecificationError, match="single-group"):
        mg.jsi(df)


def test_jsi_is_not_defined_beyond_single_group_unidimensional_normal() -> None:
    # Issue #81: no definition or reference exists for these models (DESIGN.md §16.17).
    df = _simulate(3, 400, 6)
    names = list(df.columns)
    lean = BAEM(max_iter=5)
    eh = Model.uniform(TwoPL(), items=names).with_latent(EmpiricalHistogram())
    two = Model.uniform(TwoPL(), items=names).with_factors({"F1": names[:3], "F2": names[3:]})
    for spec in (eh, two):
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")  # a few EM cycles are enough for this check
            res = fit(spec, df, method=lean, se=None)
        with pytest.raises(SpecificationError, match="has not been studied"):
            res.jsi(df)


def test_jsi_requires_x64() -> None:
    res, df = _sim_fit()
    jax.config.update("jax_enable_x64", False)  # type: ignore[no-untyped-call]
    try:
        with pytest.raises(PrecisionError):
            res.jsi(df)
    finally:
        jax.config.update("jax_enable_x64", True)  # type: ignore[no-untyped-call]
