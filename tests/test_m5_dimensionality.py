"""D2: parallel analysis, Velicer's MAP and the empirical Kaiser criterion (VALIDATION.md V25).

Deterministic parts are compared exactly with ``tests/reference/v25_dimensionality.json``
(generated by ``validation/r/m5_dimensionality_reference.R`` from the lavaan polychoric matrices of
V24): EKC with EFAtools, MAP with psych / EFA.dimensions (squared) and an independent R
implementation (fourth power), observed PCA and SMC eigenvalues. Normal-data reference eigenvalues
are compared with EFAtools' ``PARALLEL`` within Monte Carlo error.
"""

from __future__ import annotations

import json
from functools import cache
from typing import Any

import jax
import numpy as np
import pandas as pd
import pytest

from flexpyirt import empirical_kaiser, parallel_analysis, polychoric, velicer_map
from flexpyirt.dimensionality import _eigenvalues, _normal_reference, _permutations
from flexpyirt.errors import FlexpyirtWarning, PrecisionError, SpecificationError
from tests._reference import REFERENCE_DIR, check_reference_meta

EXACT = 1e-11


@cache
def _reference() -> dict[str, Any]:
    raw = dict(json.loads((REFERENCE_DIR / "v25_dimensionality.json").read_text()))
    check_reference_meta(raw["meta"])
    return raw


def _case_names() -> list[str]:
    return [c["name"] for c in _reference()["cases"]]


def _case(name: str) -> dict[str, Any]:
    return next(c for c in _reference()["cases"] if c["name"] == name)


@pytest.mark.parametrize("name", _case_names())
def test_empirical_kaiser_matches_efatools(name: str) -> None:
    case = _case(name)
    res = empirical_kaiser(np.asarray(case["correlation"]), n_obs=case["n"])
    assert res.n_factors == case["ekc_n_factors"]
    np.testing.assert_allclose(res.eigenvalues, case["ekc_eigenvalues"], rtol=0, atol=EXACT)
    np.testing.assert_allclose(res.reference, case["ekc_reference"], rtol=0, atol=EXACT)


@pytest.mark.parametrize("name", _case_names())
def test_velicer_map_matches_r(name: str) -> None:
    case = _case(name)
    corr = np.asarray(case["correlation"])
    squared = velicer_map(corr, power=2)
    np.testing.assert_allclose(squared.statistic, case["map2_efa_dimensions"], rtol=0, atol=EXACT)
    np.testing.assert_allclose(squared.statistic[1:], case["map2_psych"], rtol=0, atol=EXACT)
    assert squared.n_factors == case["map_n_factors_efa_dimensions"]
    fourth = velicer_map(corr)
    assert fourth.power == 4
    np.testing.assert_allclose(fourth.statistic, case["map4_elementwise"], rtol=0, atol=EXACT)
    assert fourth.n_factors == int(np.argmin(case["map4_elementwise"]))


@pytest.mark.parametrize("name", _case_names())
def test_observed_eigenvalues_match_r(name: str) -> None:
    case = _case(name)
    corr = np.asarray(case["correlation"])
    np.testing.assert_allclose(_eigenvalues(corr, "pca"), case["eigen_pca"], rtol=0, atol=EXACT)
    np.testing.assert_allclose(_eigenvalues(corr, "smc"), case["eigen_smc"], rtol=0, atol=EXACT)


@pytest.mark.parametrize("eigen_type", ["pca", "smc"])
@pytest.mark.parametrize("index", [0, 1, 2])
def test_normal_reference_matches_efatools_within_monte_carlo_error(
    eigen_type: str, index: int
) -> None:
    ref = _reference()["normal_reference"][index]
    reps = _normal_reference(
        jax.random.key(2501), ref["n"], ref["p"], ref["n_datasets"], eigen_type, chunk=4000
    )
    se = reps.std(axis=0) * np.sqrt(2.0 / ref["n_datasets"])
    z = (reps.mean(axis=0) - np.asarray(ref[f"{eigen_type}_mean"])) / se
    assert np.abs(z).max() <= 4.5
    p95 = np.quantile(reps, 0.95, axis=0)
    np.testing.assert_allclose(p95, ref[f"{eigen_type}_p95"], rtol=0, atol=6e-3)


def test_permutations_are_independent_permutations() -> None:
    orders = _permutations(jax.random.key(3), 4, 5, 30)
    assert orders.shape == (4, 5, 30)
    np.testing.assert_array_equal(
        np.sort(orders, axis=-1), np.broadcast_to(np.arange(30), orders.shape)
    )
    assert len({tuple(o) for o in orders.reshape(-1, 30)}) == 20


def _two_factor_binary(n: int, seed: int) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    factors = rng.normal(size=(n, 2))
    factors[:, 1] = 0.3 * factors[:, 0] + np.sqrt(1 - 0.09) * factors[:, 1]
    loadings = np.zeros((10, 2))
    loadings[:5, 0] = 0.75
    loadings[5:, 1] = 0.75
    latent = factors @ loadings.T + rng.normal(size=(n, 10)) * np.sqrt(1 - 0.75**2)
    cuts = np.linspace(-0.8, 0.8, 10)
    return pd.DataFrame((latent > cuts).astype(float), columns=[f"i{j}" for j in range(10)])


@cache
def _two_factor_pa(eigen_type: str, reference: str) -> Any:
    return parallel_analysis(
        _two_factor_binary(1200, 11),
        key=jax.random.key(5),
        eigen_type=eigen_type,  # type: ignore[arg-type]
        reference=reference,  # type: ignore[arg-type]
        n_replications=40,
    )


@pytest.mark.parametrize("eigen_type", ["pca", "smc"])
@pytest.mark.parametrize("reference", ["permutation", "normal"])
def test_parallel_analysis_recovers_two_factors(eigen_type: str, reference: str) -> None:
    res = _two_factor_pa(eigen_type, reference)
    assert res.n_factors == 2
    assert res.replications.shape == (40, 10)
    assert res.n_skipped == 0
    np.testing.assert_allclose(
        res.reference, np.quantile(res.replications, 0.95, axis=0), rtol=0, atol=0
    )
    np.testing.assert_allclose(res.reference_mean, res.replications.mean(axis=0))
    observed = polychoric(_two_factor_binary(1200, 11)).correlation.to_numpy()
    np.testing.assert_allclose(res.observed, _eigenvalues(observed, eigen_type), atol=1e-12)


def test_permutation_reference_for_polychoric_is_above_the_normal_one() -> None:
    """Tetrachoric correlations of independent items vary more than Pearson ones of normals."""
    assert (
        _two_factor_pa("pca", "permutation").reference[0]
        > _two_factor_pa("pca", "normal").reference[0]
    )


def test_parallel_analysis_is_reproducible_and_supports_mean_rule() -> None:
    data = _two_factor_binary(300, 2)
    first = parallel_analysis(data, key=jax.random.key(9), n_replications=5, quantile=None)
    second = parallel_analysis(data, key=jax.random.key(9), n_replications=5, quantile=None)
    np.testing.assert_array_equal(first.replications, second.replications)
    np.testing.assert_allclose(first.reference, first.replications.mean(axis=0))
    assert first.quantile is None
    other = parallel_analysis(data, key=jax.random.key(10), n_replications=5)
    assert not np.array_equal(first.replications, other.replications)


def test_parallel_analysis_pearson_with_missing_data() -> None:
    rng = np.random.default_rng(4)
    common = rng.normal(size=(400, 1))
    y = common + 0.6 * rng.normal(size=(400, 6))
    y[::9, 3] = np.nan
    res = parallel_analysis(y, key=jax.random.key(1), correlation="pearson", n_replications=20)
    assert res.n_factors == 1
    assert res.correlation_kind == "pearson"
    expected = pd.DataFrame(y).corr().to_numpy()
    np.testing.assert_allclose(res.correlation.to_numpy(), expected, atol=1e-12)


def test_parallel_analysis_skips_unusable_permutations(monkeypatch: pytest.MonkeyPatch) -> None:
    from flexpyirt import dimensionality

    original = dimensionality._observed_correlation
    calls = {"n": 0}

    def flaky(*args: Any, quiet: bool = False, **kwargs: Any) -> np.ndarray:
        if quiet:
            calls["n"] += 1
            if calls["n"] % 3 == 0:
                raise SpecificationError("unusable permuted pair")
        return original(*args, quiet=quiet, **kwargs)

    monkeypatch.setattr(dimensionality, "_observed_correlation", flaky)
    with pytest.warns(FlexpyirtWarning, match="3 of 9"):
        res = parallel_analysis(_two_factor_binary(200, 1), key=jax.random.key(0), n_replications=9)
    assert res.n_skipped == 3
    assert res.replications.shape == (6, 10)

    def always(*args: Any, quiet: bool = False, **kwargs: Any) -> np.ndarray:
        if quiet:
            raise SpecificationError("unusable permuted pair")
        return original(*args, quiet=quiet, **kwargs)

    monkeypatch.setattr(dimensionality, "_observed_correlation", always)
    with pytest.raises(SpecificationError, match="Fewer than two"):
        parallel_analysis(_two_factor_binary(200, 1), key=jax.random.key(0), n_replications=3)


def test_empirical_kaiser_from_polychoric_result_uses_smallest_pairwise_n() -> None:
    data = _two_factor_binary(500, 3)
    data.iloc[:40, 0] = np.nan
    pc = polychoric(data)
    res = empirical_kaiser(pc)
    assert res.n_obs == 460
    assert res.n_factors == empirical_kaiser(pc.correlation, n_obs=460).n_factors


def test_velicer_map_identity_and_dataframe_input() -> None:
    eye = pd.DataFrame(np.eye(4))
    res = velicer_map(eye, power=2)
    assert res.n_factors == 0
    assert res.statistic[0] == 0.0
    # Partialling out every component of the identity leaves nothing: undefined, reported as NaN.
    assert np.isnan(res.statistic[-1]) or res.statistic[-1] >= 0.0


@pytest.mark.parametrize(
    ("call", "match"),
    [
        (lambda: velicer_map(np.eye(4), power=3), "power"),  # type: ignore[arg-type]
        (lambda: velicer_map(np.eye(2)), "at least 3"),
        (lambda: velicer_map(np.array([[1, 0.2, 0], [0.3, 1, 0], [0, 0, 1]])), "symmetric"),
        (lambda: velicer_map(np.full((3, 3), 0.5)), "unit diagonal"),
        (lambda: empirical_kaiser(np.eye(3)), "n_obs"),
        (lambda: empirical_kaiser(np.eye(3), n_obs=0), "n_obs"),
    ],
)
def test_invalid_matrix_inputs(call: Any, match: str) -> None:
    with pytest.raises(SpecificationError, match=match):
        call()


@pytest.mark.parametrize(
    ("kwargs", "match"),
    [
        ({"correlation": "spearman"}, "correlation"),
        ({"eigen_type": "efa"}, "eigen_type"),
        ({"reference": "bootstrap"}, "reference"),
        ({"n_replications": 1}, "n_replications"),
        ({"quantile": 1.0}, "quantile"),
    ],
)
def test_invalid_parallel_analysis_options(kwargs: dict[str, Any], match: str) -> None:
    with pytest.raises(SpecificationError, match=match):
        parallel_analysis(_two_factor_binary(50, 1), key=jax.random.key(0), **kwargs)


def test_parallel_analysis_needs_three_items() -> None:
    with pytest.raises(SpecificationError, match="at least 3"):
        parallel_analysis(_two_factor_binary(50, 1).iloc[:, :2], key=jax.random.key(0))


def test_parallel_analysis_requires_x64() -> None:
    jax.config.update("jax_enable_x64", False)  # type: ignore[no-untyped-call]
    try:
        with pytest.raises(PrecisionError):
            parallel_analysis(_two_factor_binary(50, 1), key=jax.random.key(0))
    finally:
        jax.config.update("jax_enable_x64", True)  # type: ignore[no-untyped-call]
