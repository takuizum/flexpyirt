"""V42: M2* for multiple groups, missing data and MAP fits vs R mirt's ``M2()`` (VALIDATION.md).

Reference file ``tests/reference/v42_m2_groups_missing_map.json`` is generated by
``validation/r/m6_m2_groups_missing_map_reference.R`` (R mirt 1.46.1). Six simulated cases:
two-group 2PL with unequal groups and anchor items (complete and with 15% MCAR missing), two-group
GRM, two-group two-factor 2PL, single-group 2PL with 20% MCAR missing, and a 2PL MAP fit.

At mirt's estimates (the fitted result with its free vector replaced by mirt's values):

- the default ``m2()`` matches ``exact``, the formulas of DESIGN.md §16.23 recomputed in R
  (central-difference Delta over every free parameter with group rows scaled by
  ``sqrt(N_g / N)``, mirt's ``buildXi2els`` rescaled to the exact MCAR covariance of the
  pairwise-available margins, and the multiple-group independence model);
- ``_mirt_convention=True`` with ``_latent_in_delta=False`` reproduces mirt's raw ``M2()``.

flexpyirt's own fits reproduce mirt's log-likelihood (log-posterior for MAP), and their ``m2()``
agrees with ``exact`` up to the difference in the estimates.
"""

from __future__ import annotations

import dataclasses
import json
from functools import cache
from pathlib import Path
from typing import Any

import jax.numpy as jnp
import numpy as np
import pandas as pd
import pytest

from flexpyirt import (
    BAEM,
    GRM,
    FitResult,
    LogNormalPrior,
    Model,
    Normal,
    NormalPrior,
    Quadrature,
    TwoPL,
    _m2,
    fit,
)
from flexpyirt._compile import LATENT_ITEM, coerce_groups, coerce_responses, compile_problem
from tests._reference import check_reference_meta

# mirt reference comparison: nightly and release-PR CI only (CONTRIBUTING.md, "Tests").
pytestmark = pytest.mark.slow

REFERENCE_DIR = Path(__file__).parent / "reference"
CASES = (
    "twogroup_2pl",
    "twogroup_2pl_missing",
    "twogroup_grm",
    "twogroup_2d",
    "missing_2pl",
    "map_2pl",
)
DICHOTOMOUS = ("twogroup_2pl", "twogroup_2pl_missing", "twogroup_2d", "missing_2pl", "map_2pl")


@cache
def _bundle() -> dict[str, Any]:
    raw = json.loads((REFERENCE_DIR / "v42_m2_groups_missing_map.json").read_text())
    check_reference_meta(raw["meta"])
    return dict(raw["cases"])


@cache
def _source(name: str) -> tuple[Model, pd.DataFrame, np.ndarray | None, Quadrature]:
    ref = _bundle()[name]
    items = list(ref["items"])
    pats = pd.DataFrame(
        [[np.nan if v is None else float(v) for v in row] for row in ref["patterns"]],
        columns=items,
    )
    reps = np.asarray(ref["counts"], dtype=int)
    df = pats.loc[pats.index.repeat(reps)].reset_index(drop=True)
    grp = np.repeat(np.asarray(ref["pattern_groups"]), reps) if "pattern_groups" in ref else None
    quad = Quadrature.equispaced(int(ref["quadpts"]), bounds=tuple(ref["theta_lim"]))
    base = Model.uniform(TwoPL(), items=items)
    spec = {
        "twogroup_2pl": lambda: base.with_groups(
            ref=Normal.standard(), focal=Normal.free()
        ).equal_across_groups(items=ref["anchors"]),
        "twogroup_2pl_missing": lambda: base.with_groups(
            ref=Normal.standard(), focal=Normal.free()
        ).equal_across_groups(items=ref["anchors"]),
        "twogroup_grm": lambda: (
            Model.uniform(GRM(n_categories=3), items=items)
            .with_groups(ref=Normal.standard(), focal=Normal.free())
            .equal_across_groups(items=items)
        ),
        "twogroup_2d": lambda: (
            base.with_factors(ref["factors"])
            .with_groups(ref=Normal.standard(), focal=Normal.free())
            .equal_across_groups(items=items)
        ),
        "missing_2pl": lambda: base,
        "map_2pl": lambda: base.prior(param="a", dist=LogNormalPrior(*ref["prior"]["a"])).prior(
            param="d", dist=NormalPrior(*ref["prior"]["d"])
        ),
    }[name]()
    return spec, df, grp, quad


@cache
def _refit(name: str) -> FitResult:
    spec, df, grp, quad = _source(name)
    res = fit(spec, df, group=grp, method=BAEM(tol=1e-9, max_iter=20000), quadrature=quad, se=None)
    assert res.converged
    return res


def _mirt_value(estimates: dict[str, Any], group: str, item: str, param: str) -> float:
    est = estimates[group if group in estimates else "all"]
    if item == LATENT_ITEM:
        return float(est["latent"][param])
    return float(est["items"][item][param])


@cache
def _at_mirt(name: str) -> FitResult:
    """The refit with every free parameter replaced by mirt's estimate (free flags kept)."""
    res = _refit(name)
    estimates = _bundle()[name]["estimates"]
    eta = np.array(res._eta, dtype=float)
    free = res.parameters[res.parameters["free"]]
    for group, item, param, fid in zip(
        free["group"], free["item"], free["param"], free["free_id"], strict=True
    ):
        eta[int(fid)] = _mirt_value(estimates, str(group), str(item), str(param))
    assert np.max(np.abs(eta - np.asarray(res._eta))) < 5e-3
    return dataclasses.replace(res, _eta=eta)


def _srmsr_reference(ref: dict[str, Any], res: FitResult) -> dict[str, float]:
    mirt = ref["mirt"]
    if not res._model.is_multigroup:
        return {"srmsr": float(mirt["SRMSR"])}
    return {f"srmsr_{g}": float(mirt[f"SRMSR.{g}"]) for g in ref["groups"]}


@pytest.mark.parametrize("name", CASES)
def test_refit_matches_mirt_objective(name: str) -> None:
    ref = _bundle()[name]
    res = _refit(name)
    assert res.n_params == int(ref["nest"])
    if name == "map_2pl":
        assert res.log_posterior == pytest.approx(float(ref["log_posterior"]), rel=1e-7)
    else:
        assert res.loglik == pytest.approx(float(ref["loglik"]), rel=1e-7)


@pytest.mark.parametrize("name", CASES)
def test_m2_at_mirt_estimates_matches_exact(name: str) -> None:
    ref = _bundle()[name]
    ex = ref["exact"]
    _, df, grp, _ = _source(name)
    res = _at_mirt(name)
    out = res.m2(df, group=grp)
    assert len(out) == 1
    row = out.iloc[0]
    expected_cols = ["m2", "df", "p", "rmsea", "rmsea_5", "rmsea_95"]
    expected_cols += list(_srmsr_reference(ref, res))
    expected_cols += ["tli", "cfi"]
    assert list(out.columns) == expected_cols
    assert int(row["df"]) == int(ex["df"]) == int(ref["mirt"]["df"])
    np.testing.assert_allclose(row["m2"], ex["M2"], rtol=1e-6)
    np.testing.assert_allclose(row["p"], ex["p"], rtol=1e-6, atol=1e-9)
    np.testing.assert_allclose(row["rmsea"], ex["RMSEA"], rtol=1e-6, atol=1e-9)
    np.testing.assert_allclose(row["rmsea_5"], ex["RMSEA_5"], rtol=0.0, atol=1e-4)
    np.testing.assert_allclose(row["rmsea_95"], ex["RMSEA_95"], rtol=0.0, atol=1e-4)
    # SRMSR does not depend on Delta or on the weighting: it is mirt's value directly.
    for col, value in _srmsr_reference(ref, res).items():
        np.testing.assert_allclose(row[col], value, rtol=1e-7, atol=1e-10)
    if name in DICHOTOMOUS:
        np.testing.assert_allclose(row["tli"], ex["TLI"], rtol=1e-6, atol=1e-9)
        np.testing.assert_allclose(row["cfi"], ex["CFI"], rtol=1e-6, atol=1e-9)
    else:
        assert np.isnan(row["tli"]) and np.isnan(row["cfi"])


@pytest.mark.parametrize("name", CASES)
def test_mirt_convention_reproduces_mirt_raw(name: str) -> None:
    ref = _bundle()[name]
    raw = ref["mirt"]
    _, df, grp, quad = _source(name)
    res = _at_mirt(name)
    y = coerce_responses(df, res._model)
    codes, group_names = coerce_groups(grp, res._model, y.shape[0])
    prob = compile_problem(res._model, y, codes, res.parameters, quad).problem
    out = _m2.m2_statistic(
        prob,
        jnp.asarray(res._eta),
        y,
        n_params=res.n_params,
        n_categories=[m.kernel.n_categories for _, m in res._model.items],
        groups=codes,
        _latent_in_delta=False,
        _mirt_convention=True,
    )
    assert out.df == int(raw["df"])
    np.testing.assert_allclose(out.m2, raw["M2"], rtol=1e-6)
    np.testing.assert_allclose(out.rmsea, raw["RMSEA"], rtol=1e-6, atol=1e-9)
    srmsr = dict(zip(group_names, out.srmsr_by_group, strict=True))
    for col, value in _srmsr_reference(ref, res).items():
        key = col.removeprefix("srmsr_") if col != "srmsr" else group_names[0]
        np.testing.assert_allclose(srmsr[key], value, rtol=1e-7, atol=1e-10)
    if "TLI" in raw:
        # mirt's null model is fitted by EM (quadpts = 3), so its intercepts agree with the
        # available-case proportions to about 1e-7.
        np.testing.assert_allclose(out.tli, raw["TLI"], rtol=1e-6)
        np.testing.assert_allclose(out.cfi, raw["CFI"], rtol=1e-6)


@pytest.mark.parametrize("name", CASES)
def test_refit_m2_close_to_exact(name: str) -> None:
    """flexpyirt's own estimates give the same M2 up to the estimation difference."""
    ex = _bundle()[name]["exact"]
    _, df, grp, _ = _source(name)
    row = _refit(name).m2(df, group=grp).iloc[0]
    np.testing.assert_allclose(row["m2"], ex["M2"], rtol=1e-3)


def test_mirt_differs_where_documented() -> None:
    """mirt's raw value differs from the exact one most with missing data (DESIGN.md §16.23)."""
    rel = {
        name: abs(_bundle()[name]["mirt"]["M2"] - _bundle()[name]["exact"]["M2"])
        / _bundle()[name]["exact"]["M2"]
        for name in CASES
    }
    assert rel["map_2pl"] < 1e-8  # no latent columns, one group, complete data: identical
    assert rel["twogroup_2pl_missing"] > 0.1
    assert rel["missing_2pl"] > 0.03
