"""V18: M2 / M2* limited-information goodness of fit vs R mirt's ``M2()`` (VALIDATION.md).

Reference file ``tests/reference/v18_m2.json`` is generated by ``validation/r/m5_m2_reference.R``
using R mirt 1.46.1. Six cases are checked with both plain EM and SQUAREM:

- ``lsat7_2pl``, ``sim_2pl`` (2PL): compared directly against mirt's ``M2()`` (including TLI/CFI).
- ``grm_sim`` (GRM, K=3): compared directly against mirt's ``M2()``; ``tli`` and ``cfi`` are NaN
  because the polytomous null model's Jacobian is rank-deficient under item-score moments
  (DESIGN.md §16.3).
- ``rasch_free_var`` (Rasch with free latent variance): mirt drops free latent parameters from
  Delta while subtracting them in ``df``. flexpyirt includes them by default (matching R's
  ``exact_with_latent``); internal ``_latent_in_delta=False`` reproduces mirt's raw ``M2()``.
- ``threepl`` (3PL) and ``gpcm_sim`` (GPCM, K=4): mirt 1.46.1 has confirmed bugs in ``dP("dich")``
  (uses the 2PL derivative ``P_0 * P_1``) and ``dP("gpcm")`` (omits division by ``den`` in the
  slope derivative). ``df`` and ``SRMSR`` match mirt directly; ``M2`` and derived indices match
  the exact R ``M2*`` reference (central-difference derivatives + mirt's ``buildXi2els``) while
  mirt's raw ``M2`` shows the documented discrepancy.
"""

from __future__ import annotations

import json
from functools import cache
from pathlib import Path
from typing import Any

import jax.numpy as jnp
import numpy as np
import pandas as pd
import pytest

from flexpyirt import (
    BAEM,
    GPCM,
    GRM,
    FitResult,
    Model,
    Quadrature,
    Rasch,
    ThreePL,
    TwoPL,
    _m2,
    fit,
)
from flexpyirt._compile import LATENT_ITEM, coerce_groups, coerce_responses, compile_problem
from tests._reference import check_reference_meta

# mirt reference comparison: nightly and release-PR CI only (CONTRIBUTING.md, "Tests").
pytestmark = pytest.mark.slow

REFERENCE_DIR = Path(__file__).parent / "reference"
SQUAREM = (False, True)
CASES = ("lsat7_2pl", "sim_2pl", "threepl", "rasch_free_var", "grm_sim", "gpcm_sim")
M2_COLUMNS = ["m2", "df", "p", "rmsea", "rmsea_5", "rmsea_95", "srmsr", "tli", "cfi"]


@cache
def _bundle() -> dict[str, Any]:
    raw = json.loads((REFERENCE_DIR / "v18_m2.json").read_text())
    check_reference_meta(raw["meta"])
    return dict(raw["cases"])


@cache
def _case_data(name: str) -> tuple[pd.DataFrame, Quadrature, list[str], dict[str, Any]]:
    ref = _bundle()[name]
    if ref["source"]:
        src = json.loads((REFERENCE_DIR / f"{ref['source']}.json").read_text())
        items = list(src["items"])
        pats = pd.DataFrame(np.asarray(src["patterns"], dtype=float), columns=items)
        df = pats.loc[pats.index.repeat(src["counts"])].reset_index(drop=True)
        quad = Quadrature.equispaced(
            int(src["meta"]["quadpts"]),
            bounds=(float(src["meta"]["theta_lim"][0]), float(src["meta"]["theta_lim"][1])),
        )
        return df, quad, items, src
    items = list(ref["items"])
    pats = pd.DataFrame(np.asarray(ref["patterns"], dtype=float), columns=items)
    df = pats.loc[pats.index.repeat(ref["counts"])].reset_index(drop=True)
    quad = Quadrature.equispaced(61, bounds=(-6.0, 6.0))
    return df, quad, items, ref


def _build_spec(name: str, items: list[str]) -> Model:
    return {
        "lsat7_2pl": lambda: Model.uniform(TwoPL(), items=items),
        "sim_2pl": lambda: Model.uniform(TwoPL(), items=items),
        "threepl": lambda: Model.uniform(ThreePL(), items=items),
        "rasch_free_var": lambda: Model.uniform(Rasch(), items=items),
        "grm_sim": lambda: Model.uniform(GRM(n_categories=3), items=items),
        "gpcm_sim": lambda: Model.uniform(GPCM(n_categories=4), items=items),
    }[name]()


@cache
def _fit(name: str, squarem: bool = False) -> FitResult:
    df, quad, items, _ = _case_data(name)
    spec = _build_spec(name, items)
    return fit(
        spec,
        df,
        method=BAEM(tol=1e-9, max_iter=20000, squarem=squarem),
        quadrature=quad,
        se=None,
    )


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", CASES)
def test_loglik_matches_reference(name: str, squarem: bool) -> None:
    ref = _bundle()[name]
    res = _fit(name, squarem)
    assert res.converged
    assert res.n_params == int(ref["nest"])
    assert abs(res.loglik - float(ref["loglik"])) <= 1e-6 * abs(float(ref["loglik"]))


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", ("lsat7_2pl", "sim_2pl", "grm_sim"))
def test_m2_matches_mirt_directly(name: str, squarem: bool) -> None:
    ref = _bundle()[name]
    df, _, _, _ = _case_data(name)
    out = _fit(name, squarem).m2(df)
    assert list(out.columns) == M2_COLUMNS
    assert len(out) == 1
    row = out.iloc[0]
    assert int(row["df"]) == int(ref["df"])
    np.testing.assert_allclose(row["m2"], ref["M2"], rtol=1e-6)
    np.testing.assert_allclose(row["p"], ref["p"], rtol=1e-6, atol=1e-8)
    np.testing.assert_allclose(row["rmsea"], ref["RMSEA"], rtol=1e-6, atol=1e-8)
    np.testing.assert_allclose(row["rmsea_5"], ref["RMSEA_5"], rtol=0.0, atol=1e-4)
    np.testing.assert_allclose(row["rmsea_95"], ref["RMSEA_95"], rtol=0.0, atol=1e-4)
    np.testing.assert_allclose(row["srmsr"], ref["SRMSR"], rtol=1e-6, atol=1e-8)
    if name == "grm_sim":
        assert np.isnan(row["tli"])
        assert np.isnan(row["cfi"])
    else:
        np.testing.assert_allclose(row["tli"], ref["TLI"], rtol=1e-6, atol=1e-8)
        np.testing.assert_allclose(row["cfi"], ref["CFI"], rtol=1e-6, atol=1e-8)


@pytest.mark.parametrize("squarem", SQUAREM)
@pytest.mark.parametrize("name", ("threepl", "gpcm_sim"))
def test_m2_threepl_and_gpcm_match_exact_r_reference(name: str, squarem: bool) -> None:
    """Compare 3PL and GPCM against exact R M2* (avoiding mirt 1.46.1's dP bugs)."""
    ref = _bundle()[name]
    ex = ref["exact"]
    df, _, _, _ = _case_data(name)
    out = _fit(name, squarem).m2(df)
    assert list(out.columns) == M2_COLUMNS
    assert len(out) == 1
    row = out.iloc[0]

    # df and SRMSR do not use dP and match mirt's raw output directly.
    assert int(row["df"]) == int(ref["df"])
    np.testing.assert_allclose(row["srmsr"], ref["SRMSR"], rtol=1e-6, atol=1e-8)

    # M2 and derived indices match the exact R reference (exact derivatives + mirt's buildXi2els).
    np.testing.assert_allclose(row["m2"], ex["M2"], rtol=1e-6)
    np.testing.assert_allclose(row["p"], ex["p"], rtol=1e-6, atol=1e-8)
    np.testing.assert_allclose(row["rmsea"], ex["RMSEA"], rtol=1e-6, atol=1e-8)
    np.testing.assert_allclose(row["rmsea_5"], ex["RMSEA_5"], rtol=0.0, atol=1e-4)
    np.testing.assert_allclose(row["rmsea_95"], ex["RMSEA_95"], rtol=0.0, atol=1e-4)
    if name == "threepl":
        np.testing.assert_allclose(row["tli"], ex["TLI"], rtol=1e-6, atol=1e-8)
        np.testing.assert_allclose(row["cfi"], ex["CFI"], rtol=1e-6, atol=1e-8)
        assert abs(float(row["m2"]) - float(ref["M2"])) / float(row["m2"]) > 0.04
    else:
        assert np.isnan(row["tli"])
        assert np.isnan(row["cfi"])
        assert abs(float(row["m2"]) - float(ref["M2"])) / float(row["m2"]) > 0.10


@pytest.mark.parametrize("squarem", SQUAREM)
def test_m2_rasch_free_var_latent_in_delta(squarem: bool) -> None:
    """Rasch with free latent variance: default includes latent in Delta; False matches mirt."""
    ref = _bundle()["rasch_free_var"]
    ex_lat = ref["exact_with_latent"]
    df, quad, _items, src = _case_data("rasch_free_var")
    res = _fit("rasch_free_var", squarem)
    out = res.m2(df)
    assert list(out.columns) == M2_COLUMNS
    row = out.iloc[0]

    # Default (_latent_in_delta=True): differs from mirt's M2 and matches exact_with_latent
    # (within 2e-5 on refit due to the documented 7.9e-5 exact vs closed-form latent M-step
    # variance difference on [-6, 6]; verified to 1e-8 at mirt's exact estimates below).
    assert int(row["df"]) == int(ref["df"])
    assert abs(float(row["m2"]) - float(ref["M2"])) > 1e-2
    np.testing.assert_allclose(row["m2"], ex_lat["M2"], rtol=2e-5)
    np.testing.assert_allclose(row["p"], ex_lat["p"], rtol=1e-4, atol=3e-5)
    np.testing.assert_allclose(row["rmsea"], ex_lat["RMSEA"], rtol=1e-4, atol=1e-6)
    np.testing.assert_allclose(row["rmsea_5"], ex_lat["RMSEA_5"], rtol=0.0, atol=1e-4)
    np.testing.assert_allclose(row["rmsea_95"], ex_lat["RMSEA_95"], rtol=0.0, atol=1e-4)
    np.testing.assert_allclose(row["srmsr"], ref["SRMSR"], rtol=2e-5, atol=1e-6)
    np.testing.assert_allclose(row["tli"], ex_lat["TLI"], rtol=1e-5, atol=1e-6)
    np.testing.assert_allclose(row["cfi"], ex_lat["CFI"], rtol=1e-5, atol=1e-6)

    # Evaluate at mirt's exact parameter estimates (keeping free flags) to isolate the M2 formula.
    y = coerce_responses(df, res._model)
    codes, _ = coerce_groups(None, res._model, y.shape[0], require_all=False)
    compiled = compile_problem(res._model, y, codes, res.parameters, quad)
    n_categories = [m.kernel.n_categories for _, m in res._model.items]

    # Map mirt's estimates into eta order.
    eta_mirt = np.empty_like(res._eta)
    free_rows = res.parameters[res.parameters["free"]]
    for _, prow in free_rows.iterrows():
        fid = int(prow["free_id"])
        if prow["item"] == LATENT_ITEM:
            eta_mirt[fid] = float(src["latent"][prow["param"]])
        else:
            eta_mirt[fid] = float(src["params"][prow["item"]][prow["param"]])
    eta_j = jnp.asarray(eta_mirt)

    # _latent_in_delta=False reproduces mirt's raw M2() to machine/reference precision.
    m2_nolat = _m2.m2_statistic(
        compiled.problem,
        eta_j,
        y,
        n_params=res.n_params,
        n_categories=n_categories,
        _latent_in_delta=False,
    )
    assert m2_nolat.df == int(ref["df"])
    np.testing.assert_allclose(m2_nolat.m2, ref["M2"], rtol=1e-9)
    np.testing.assert_allclose(m2_nolat.p, ref["p"], rtol=1e-9, atol=1e-10)
    np.testing.assert_allclose(m2_nolat.rmsea, ref["RMSEA"], rtol=1e-9, atol=1e-10)
    np.testing.assert_allclose(m2_nolat.rmsea_lower, ref["RMSEA_5"], rtol=0.0, atol=1e-4)
    np.testing.assert_allclose(m2_nolat.rmsea_upper, ref["RMSEA_95"], rtol=0.0, atol=1e-4)
    np.testing.assert_allclose(m2_nolat.srmsr, ref["SRMSR"], rtol=1e-9, atol=1e-10)
    np.testing.assert_allclose(m2_nolat.tli, ref["TLI"], rtol=1e-7, atol=1e-8)
    np.testing.assert_allclose(m2_nolat.cfi, ref["CFI"], rtol=1e-7, atol=1e-8)

    # _latent_in_delta=True at mirt's estimates reproduces exact_with_latent to ~1e-8.
    m2_lat = _m2.m2_statistic(
        compiled.problem,
        eta_j,
        y,
        n_params=res.n_params,
        n_categories=n_categories,
        _latent_in_delta=True,
    )
    np.testing.assert_allclose(m2_lat.m2, ex_lat["M2"], rtol=1e-7)
    np.testing.assert_allclose(m2_lat.p, ex_lat["p"], rtol=1e-7, atol=1e-8)
    np.testing.assert_allclose(m2_lat.rmsea, ex_lat["RMSEA"], rtol=1e-7, atol=1e-8)
    np.testing.assert_allclose(m2_lat.rmsea_lower, ex_lat["RMSEA_5"], rtol=0.0, atol=1e-4)
    np.testing.assert_allclose(m2_lat.rmsea_upper, ex_lat["RMSEA_95"], rtol=0.0, atol=1e-4)
    np.testing.assert_allclose(m2_lat.srmsr, ref["SRMSR"], rtol=1e-9, atol=1e-10)
    np.testing.assert_allclose(m2_lat.tli, ex_lat["TLI"], rtol=1e-7, atol=1e-8)
    np.testing.assert_allclose(m2_lat.cfi, ex_lat["CFI"], rtol=1e-7, atol=1e-8)
    assert abs(m2_lat.m2 - m2_nolat.m2) > 0.03
